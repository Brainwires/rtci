//! DTLS 1.2 handshakes recorded between `openssl s_client` and `openssl s_server` (OpenSSL
//! 3.5.4, loopback inside a container), for the known-answer tests in `openssl_kat_test.rs`.
//!
//! Recorded with, for each cipher suite:
//!
//! ```text
//! openssl s_server -dtls1_2 -listen -port 4444 -cipher <suite> -no_ticket \
//!     -use_srtp SRTP_AES128_CM_SHA1_80 -keylogfile server.keys -msg -debug -quiet \
//!     (-psk 0102030405060708090a0b0c0d0e0f10 -psk_identity rtcdtls -nocert | -key key.pem -cert cert.pem)
//! openssl s_client -dtls1_2 -connect 127.0.0.1:4444 -cipher <suite> \
//!     -use_srtp SRTP_AES128_CM_SHA1_80 -keylogfile client.keys -msg -debug \
//!     -keymatexport EXTRACTOR-dtls_srtp -keymatexportlen 60 (-psk ... -psk_identity rtcdtls)
//! ```
//!
//! `-msg` prints every handshake message in the clear (the Finished ones included), `-debug`
//! the datagrams as sent, the key log the master secret, and `-keymatexport` the RFC 5705
//! exporter output. `-listen` makes the server run the cookie exchange, so each handshake has
//! two ClientHellos and a HelloVerifyRequest. The values below are those outputs, unedited.

use crate::cipher_suite::CipherSuiteId;

/// One handshake message as `-msg` printed it: the 12-byte DTLS handshake header and the body.
pub(crate) struct Message {
    pub(crate) from_client: bool,
    /// The epoch of the record it travelled in.
    pub(crate) epoch: u16,
    pub(crate) bytes: &'static [u8],
}

pub(crate) struct Recording {
    pub(crate) suite: CipherSuiteId,
    /// Whether the suite is a PSK suite (the premaster secret is then known: RFC 4279).
    pub(crate) psk: bool,
    /// From the key log (`CLIENT_RANDOM <random> <master secret>`).
    pub(crate) master_secret: &'static [u8],
    /// `Keying material:` for the label `EXTRACTOR-dtls_srtp`, 60 bytes.
    pub(crate) exporter: &'static [u8],
    /// Every handshake message, in the order the client sent or received it.
    pub(crate) handshake: &'static [Message],
    /// The record that carried the client's Finished, as sent.
    pub(crate) client_finished_record: &'static [u8],
    /// The record that carried the server's Finished, as sent.
    pub(crate) server_finished_record: &'static [u8],
    /// The client's protected close_notify alert, as sent.
    pub(crate) client_close_notify_record: &'static [u8],
    /// The client's first datagram: the ClientHello without a cookie.
    pub(crate) first_client_hello_datagram: &'static [u8],
    /// The server's first datagram: the HelloVerifyRequest.
    pub(crate) hello_verify_request_datagram: &'static [u8],
}

