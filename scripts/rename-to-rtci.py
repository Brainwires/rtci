#!/usr/bin/env python3
"""Rename the engine's crates from `rtc` / `rtc-*` to `rtci` / `rtci-*` (docs/rename.md).

The root crate `rtc` becomes `rtci`, every `rtc-<x>` crate `rtci-<x>` (library `rtc_<x>` ->
`rtci_<x>`), crate directories follow (`git mv`, so history follows), the repository becomes
`Brainwires/rtci` and the version line restarts at 0.1.0.

The crate names come from `cargo metadata` at run time (the root workspace and every nested
workspace: fuzz crates, the test environment's peers, ...), so crates a later branch adds are
renamed too and nothing else is. Matching is token-aware and depends on the file type; what is
deliberately left (upstream's names and URLs, history, fixtures, vendored files, the word "rtc"
in prose and identifiers such as `rtc_pc`) is printed afterwards, grouped by reason.

Usage:
  python3 scripts/rename-to-rtci.py              apply the rename to the working tree
  python3 scripts/rename-to-rtci.py --dry-run    print every planned change and counts per category
  python3 scripts/rename-to-rtci.py --check      exit 1 if any old name remains to rename (CI gate)
  python3 scripts/rename-to-rtci.py --residue    print what is deliberately left, by reason

Options: --root DIR (default: the git work tree of the current directory), --no-fmt (do not
run cargo fmt), --no-lock (do not regenerate committed Cargo.lock files), --quiet,
--manifest-report (what crates.io needs, per publishable crate).

Deterministic and idempotent: a second run changes nothing. The one-time steps (version reset,
lineage text, changelog entry, the release table row, the publication list and the parity tooling
patch) run only while the tree still has crates under the old names. Standard library only.
"""

