# Crates


@dataclass
class Crate:
    name: str  # current name
    old: str
    new: str
    old_lib: str
    new_lib: str
    manifest: str  # relative to the root
    publish: bool
    kinds: set[str] = field(default_factory=set)
    deps: list[dict] = field(default_factory=list)
    description: str | None = None
    license: str | None = None
    repository: str | None = None
    readme: str | None = None
    documentation: str | None = None


def is_ours(name: str) -> bool:
    return name in (OLD_ROOT, NEW_ROOT) or name.startswith(OLD_ROOT + "-") or name.startswith(NEW_ROOT + "-")


def old_of(name: str) -> str:
    if name == NEW_ROOT or name.startswith(NEW_ROOT + "-") or name.startswith(NEW_ROOT + "_"):
        return OLD_ROOT + name[len(NEW_ROOT):]
    return name


def new_of(name: str) -> str:
    if name == NEW_ROOT or name.startswith(NEW_ROOT + "-") or name.startswith(NEW_ROOT + "_"):
        return name
    return NEW_ROOT + name[len(OLD_ROOT):]


def run(cmd: list[str], cwd: Path, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=check)


def tracked_files(root: Path) -> list[str]:
    out = run(["git", "ls-files", "-z"], root).stdout
    return sorted(p for p in out.split("\0") if p and (root / p).is_file())


def workspace_manifests(root: Path, files: list[str]) -> list[str]:
    out = []
    for p in files:
        if not p.endswith("Cargo.toml") or excluded(p):
            continue
        text = (root / p).read_text(encoding="utf-8", errors="replace")
        if p == "Cargo.toml" or re.search(r"^\[workspace\]", text, re.M):
            out.append(p)
    return out


def metadata(root: Path, manifest: str) -> dict | None:
    for extra in (["--offline"], []):
        r = run(
            ["cargo", "metadata", "--no-deps", "--format-version", "1", "--manifest-path", manifest, *extra],
            root,
            check=False,
        )
        if r.returncode == 0:
            return json.loads(r.stdout)
    return None


def discover_crates(root: Path, files: list[str], quiet: bool) -> tuple[list[Crate], list[str]]:
    crates: dict[str, Crate] = {}
    workspaces = workspace_manifests(root, files)
    for ws in workspaces:
        md = metadata(root, ws)
        if md is None:
            warn(f"cargo metadata failed for {ws}; reading its [package] tables instead", quiet)
            continue
        for pkg in md["packages"]:
            if not is_ours(pkg["name"]):
                continue
            rel = os.path.relpath(pkg["manifest_path"], root).replace(os.sep, "/")
            if rel.startswith(".."):
                continue
            kinds = {k for t in pkg["targets"] for k in t["kind"]}
            lib = next(
                (t["name"] for t in pkg["targets"] if set(t["kind"]) & {"lib", "rlib", "dylib", "cdylib", "staticlib", "proc-macro"}),
                pkg["name"].replace("-", "_"),
            )
            old = old_of(pkg["name"])
            readme = pkg.get("readme")
            crates[rel] = Crate(
                name=pkg["name"],
                old=old,
                new=new_of(pkg["name"]),
                old_lib=old_of(lib),
                new_lib=new_of(lib) if lib.startswith(OLD_ROOT) else lib,
                manifest=rel,
                publish=pkg.get("publish") != [],
                kinds=kinds,
                deps=pkg.get("dependencies", []),
                description=pkg.get("description"),
                license=pkg.get("license") or pkg.get("license_file"),
                repository=pkg.get("repository"),
                readme=readme,
                documentation=pkg.get("documentation"),
            )
    # Safety net: a tracked manifest of ours that no workspace listed.
    for p in files:
        if not p.endswith("Cargo.toml") or excluded(p) or p in crates or tomllib is None:
            continue
        try:
            data = tomllib.loads((root / p).read_text(encoding="utf-8"))
        except Exception:
            continue
        name = data.get("package", {}).get("name")
        if isinstance(name, str) and is_ours(name):
            lib = data.get("lib", {}).get("name") or name.replace("-", "_")
            crates[p] = Crate(
                name=name,
                old=old_of(name),
                new=new_of(name),
                old_lib=old_of(lib),
                new_lib=new_of(lib) if lib.startswith(OLD_ROOT) else lib,
                manifest=p,
                publish=data.get("package", {}).get("publish", True) is not False,
            )
    return sorted(crates.values(), key=lambda c: c.manifest), workspaces


def warn(msg: str, quiet: bool = False) -> None:
    print(f"warning: {msg}", file=sys.stderr)


