def publish_order(crates: list[Crate]) -> tuple[list[str], list[str]]:
    """Dependency order for `cargo publish` (normal and build dependencies; dev-dependencies too
    when that leaves no cycle), ties by name. Returns (order, notes)."""
    pub = {c.new: c for c in crates if c.publish}
    by_old = {c.old: c.new for c in crates}
    by_any = {**by_old, **{c.new: c.new for c in crates}}
    notes = []

    def edges(with_dev):
        e = {n: set() for n in pub}
        for c in pub.values():
            for d in c.deps:
                target = by_any.get(d.get("name"))
                if target is None or target == c.new or "path" not in d:
                    continue
                kind = d.get("kind")
                if kind == "dev" and (not with_dev or d.get("req") in (None, "*")):
                    continue
                if target not in pub:
                    if kind != "dev":
                        notes.append(f"{c.new} depends on {target}, which is not published")
                    elif d.get("req") not in (None, "*"):
                        notes.append(f"{c.new} has a versioned dev-dependency on {target}, which is not published (cargo publish keeps it)")
                    continue
                e[c.new].add(target)
        return e

    def topo(e):
        order, done = [], set()
        while len(order) < len(e):
            ready = sorted(n for n in e if n not in done and e[n] <= done)
            if not ready:
                return None
            order.append(ready[0])
            done.add(ready[0])
        return order

    order = topo(edges(True))
    if order is None:
        notes.append("dev-dependencies form a cycle; order uses normal and build dependencies only")
        order = topo(edges(False)) or sorted(pub)
    return order, sorted(set(notes))


def release_publish_block(text: str, order: list[str]) -> str:
    """Replace the commented `cargo publish -p ...` lines in release.yml with the full list."""
    lines = text.split("\n")
    idx = [i for i, l in enumerate(lines) if re.match(r"^\s*#\s+cargo publish -p ", l) or re.match(r"^\s*#\s+# \.\.\. remaining crates", l)]
    if not idx:
        return text
    first, last = idx[0], idx[-1]
    indent = re.match(r"^(\s*#\s+)", lines[first]).group(1)
    block = [f"{indent}cargo publish -p {n} --token ${{{{ secrets.CRATES_IO_TOKEN }}}}" for n in order]
    block.insert(0, f"{indent}# Dependency order, generated by scripts/rename-to-rtci.py from cargo metadata.")
    return "\n".join(lines[:first] + block + lines[last + 1 :])


