# Cargo.toml


DEP_SECTION = re.compile(r"^(?:target\..+\.)?(?:dependencies|dev-dependencies|build-dependencies)$|^workspace\.dependencies$|^patch\..+$")


def toml_section_parts(header: str) -> list[str]:
    parts, cur, quote = [], "", None
    for ch in header:
        if quote:
            cur += ch
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
            cur += ch
        elif ch == ".":
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [p.strip() for p in parts]


def cargo_toml(r: Renamer, path: str, text: str, crate: Crate | None, events: list[Event], ffi_scope: bool = False) -> str:
    """Cargo.toml: package names, dependency keys and `package =`, [patch] / [replace], feature
    references, documentation / repository, versions; then the common rules for the rest."""
    lines = text.split("\n")
    ours_path_keys: set[str] = set()  # dependency keys of this manifest that are our crates
    # Pass 1: which old-name dependency keys point at our crates (path or workspace = true).
    section = None
    for i, line in enumerate(lines):
        h = re.match(r"^\s*\[\[?([^\]]+)\]\]?\s*(?:#.*)?$", line)
        if h:
            section = h.group(1).strip()
            parts = toml_section_parts(section)
            if len(parts) >= 2 and DEP_SECTION.match(".".join(parts[:-1])) and parts[-1].strip("\"'") in r.pkg:
                body = []
                for nxt in lines[i + 1 :]:
                    if re.match(r"^\s*\[", nxt):
                        break
                    body.append(nxt)
                if any(re.match(r"^\s*(path|workspace)\s*=", b) for b in body):
                    ours_path_keys.add(parts[-1].strip("\"'"))
            continue
        if section and DEP_SECTION.match(section):
            k = re.match(r"^\s*([A-Za-z0-9_-]+)(\.workspace\s*=\s*true|\s*=\s*\{.*\b(?:path|workspace)\s*=)", line)
            if k and k.group(1) in r.pkg:
                ours_path_keys.add(k.group(1))
    # Pass 2: rewrite.
    out = []
    section = None
    dotted_dep_ours = False
    for i, line in enumerate(lines):
        ctx = (path, i + 1)
        code, comment = split_comment(line)
        h = re.match(r"^(\s*\[\[?)([^\]]+)(\]\]?\s*)$", code)
        if h:
            section = h.group(2).strip()
            parts = toml_section_parts(section)
            dotted_dep_ours = False
            if len(parts) >= 2 and DEP_SECTION.match(".".join(parts[:-1])):
                key = parts[-1].strip("\"'")
                if key in ours_path_keys:
                    dotted_dep_ours = True
                    if key in r.pkg:
                        parts[-1] = parts[-1].replace(key, r.pkg[key])
                        events.append(Event(path, i + 1, "cargo-dependency", key, r.pkg[key]))
                elif key in (c.new for c in r.crates):
                    dotted_dep_ours = True
            # [profile.<name>.package.<crate>]: per-package profile settings.
            if parts[0] == "profile" and len(parts) >= 4 and parts[2] == "package":
                key = parts[3].strip("\"'")
                if key in r.pkg:
                    parts[3] = parts[3].replace(key, r.pkg[key])
                    events.append(Event(path, i + 1, "cargo-profile-package", key, r.pkg[key]))
            if parts[0] == "replace" and len(parts) >= 2:
                m = re.match(r'^(["\'])(rtc(?:-[a-z0-9-]+)?)(:.*)$', parts[1])
                if m and m.group(2) in r.pkg:
                    parts[1] = m.group(1) + r.pkg[m.group(2)] + m.group(3)
                    events.append(Event(path, i + 1, "cargo-dependency", m.group(2), r.pkg[m.group(2)]))
            new_header = h.group(1) + ".".join(parts) + h.group(3)
            # Keep the original spacing of an untouched header.
            code = new_header if new_header.replace(" ", "") != code.replace(" ", "") else code
            section_now = section
            line = code + comment
            line = r.common(line, events, ctx, "cargo", ffi_scope=ffi_scope)
            out.append(line)
            section = section_now
            continue
        # [package] / [workspace.package]
        if section == "package":
            code = sub_record(r'^(\s*name\s*=\s*")(rtc)(")', code, lambda m: m.group(1) + NEW_ROOT + m.group(3), "cargo-package-name", events, ctx)
            code = sub_record(
                r'^(\s*documentation\s*=\s*"https://docs\.rs/)(rtc(?:-[a-z0-9-]+)?)(")',
                code,
                lambda m: m.group(1) + r.pkg.get(m.group(2), m.group(2)) + m.group(3),
                "cargo-docs-url",
                events,
                ctx,
            )
            if crate and crate.publish and not r.renamed_state:
                code = sub_record(
                    r'^(\s*version\s*=\s*")((?!' + re.escape(NEW_VERSION) + r'")[^"]+)(")',
                    code,
                    lambda m: m.group(1) + NEW_VERSION + m.group(3),
                    "version",
                    events,
                    ctx,
                )
        if section in ("package", "workspace.package"):
            code = sub_record(
                r'^(\s*repository\s*=\s*")' + re.escape(UPSTREAM_REPO_URL) + r'(/?")',
                code,
                lambda m: m.group(1) + f"https://github.com/{NEW_REPO}" + '"',
                "cargo-repository",
                events,
                ctx,
            )
        if section == "workspace.package" and not r.renamed_state:
            code = sub_record(
                r'^(\s*version\s*=\s*")((?!' + re.escape(NEW_VERSION) + r'")[^"]+)(")',
                code,
                lambda m: m.group(1) + NEW_VERSION + m.group(3),
                "version",
                events,
                ctx,
            )
        if section and DEP_SECTION.match(section):
            k = re.match(r"^(\s*)([A-Za-z0-9_-]+)(\b.*)$", code)
            if k and k.group(2) == OLD_ROOT and OLD_ROOT in ours_path_keys:
                code = k.group(1) + NEW_ROOT + k.group(3)
                events.append(Event(path, i + 1, "cargo-dependency", OLD_ROOT, NEW_ROOT))
            # package = "rtc"
            code = sub_record(r'(\bpackage\s*=\s*")(rtc)(")', code, lambda m: m.group(1) + NEW_ROOT + m.group(3), "cargo-dependency", events, ctx)
            # Version requirement of a dependency on one of our crates.
            entry_ours = False
            k = re.match(r"^\s*([A-Za-z0-9_-]+)\s*=\s*\{(.*)\}", code)
            if k:
                pkgname = re.search(r'\bpackage\s*=\s*"([^"]+)"', k.group(2))
                name = pkgname.group(1) if pkgname else k.group(1)
                entry_ours = is_ours(name) and re.search(r"\b(?:path|workspace)\s*=", k.group(2)) is not None
            if (entry_ours or (dotted_dep_ours and re.match(r"^\s*version\s*=", code))) and not r.renamed_state:
                code = sub_record(
                    r'(\bversion\s*=\s*")((?!' + re.escape(NEW_VERSION) + r'")[^"]+)(")',
                    code,
                    lambda m: m.group(1) + NEW_VERSION + m.group(3),
                    "version",
                    events,
                    ctx,
                )
        if section == "features":
            for key in sorted(ours_path_keys):
                if key == OLD_ROOT:
                    code = sub_record(r'("(?:dep:)?)(rtc)(?=[/?"])', code, lambda m: m.group(1) + NEW_ROOT, "cargo-feature-ref", events, ctx)
        line = code + comment
        out.append(r.common(line, events, ctx, "cargo", ffi_scope=ffi_scope))
    return "\n".join(out)


def sub_record(pattern, text, repl, category, events, ctx):
    def cb(m):
        new = repl(m)
        if new != m.group(0):
            events.append(Event(ctx[0], ctx[1], category, m.group(0).strip(), new.strip()))
        return new

    return re.sub(pattern, cb, text)


