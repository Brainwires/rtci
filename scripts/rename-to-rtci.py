def section_rules_for(path: str):
    return SECTION_RULES.get(path)


def split_cells(line: str) -> list[str] | None:
    if not line.lstrip().startswith("|"):
        return None
    # Split on | outside code spans.
    cells, cur, tick = [], "", False
    s = line.strip()
    for ch in s[1:]:
        if ch == "`":
            tick = not tick
        if ch == "|" and not tick:
            cells.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        cells.append(cur)
    return cells


def rewrite_file(r: Renamer, path: str, text: str, events: list[Event], residue: list[Residue], crate_by_manifest: dict) -> str:
    cls = file_class(path)
    reason = excluded(path)
    if reason or cls is None:
        if reason:
            for i, line in enumerate(text.split("\n")):
                for m in RESIDUE_RE.finditer(line):
                    residue.append(Residue(path, i + 1, reason, line.strip()))
        return text
    ffi_scope = any(path.startswith(d + "/") for d in r.ffi_dirs) or (bool(r.ffi_dirs) and r.ffi_scope_re.search(text) is not None)
    if cls == "cargo":
        # Cargo.toml is structured; its residue is classified like prose.
        new = cargo_toml(r, path, text, crate_by_manifest.get(path), events, ffi_scope=ffi_scope)
        scan_residue(r, path, new.split("\n"), residue, cls)
        return new

    exceptions = exceptions_for(path)
    lines = text.split("\n")
    out = []
    rules = section_rules_for(path)
    section = ""
    fence = None  # language of the open code block
    in_marker = False
    changelog = path == "CHANGELOG.md"
    changelog_live = False
    exempt_reason: list[str | None] = []
    for i, line in enumerate(lines):
        ctx = (path, i + 1)
        exempt = None
        if MARKER_START.search(line):
            in_marker = True
        if in_marker:
            exempt = "lineage or rename statement (names the old crates on purpose)"
        if MARKER_END.search(line):
            in_marker = False
        if changelog:
            if re.match(r"^## \[", line):
                changelog_live = line.startswith("## [Unreleased]")
            if not changelog_live and exempt is None:
                exempt = "released CHANGELOG section (history)"
        if cls == "prose" and path.endswith(".md"):
            hm = re.match(r"^#{1,6}\s+(.*)$", line)
            if hm and fence is None:
                section = hm.group(1).strip()
            fm = re.match(r"^\s*(```+|~~~+)\s*([A-Za-z0-9_+-]*)", line)
            if fm:
                fence = None if fence is not None else (fm.group(2) or "text").lower()
                exempt_reason.append(exempt)
                out.append(line)
                continue
        if exempt:
            exempt_reason.append(exempt)
            out.append(line)
            continue
        new = line
        if cls == "rust":
            new = r.rust(line, events, ctx, ffi_scope=ffi_scope)
        elif cls == "c":
            new = r.common(line, events, ctx, "c", ffi_scope=True)
        elif cls in ("code", "shell"):
            new = r.code(line, events, ctx, path, shell=(cls == "shell"), ffi_scope=ffi_scope, exceptions=exceptions)
        elif cls == "plain":
            new = r.plain(line, events, ctx, ffi_scope=ffi_scope)
        else:  # prose
            rule = None
            if rules:
                rule = rules.get("*") or next((v for k, v in rules.items() if section.startswith(k)), None)
            cells = split_cells(line) if rule else None
            if fence in ("rust", "rs", "no_run", "ignore", "should_panic", "compile_fail", "edition2021", "edition2024"):
                new = r.rust(line, events, ctx, ffi_scope=ffi_scope)
            elif fence == "toml":
                new = r.toml_snippet(line, events, ctx)
            elif fence is not None:
                new = r.code(line, events, ctx, path, shell=fence in SHELL_FENCES, ffi_scope=ffi_scope)
            elif rule and cells is not None and rule.get("keep_rows") and not re.match(r"^\s*\|[\s:|-]+\|\s*$", line):
                exempt_reason.append("upstream test parity table (upstream crate names as keys)")
                out.append(line)
                continue
            elif rule and cells is not None and rule.get("keep_columns"):
                keep = rule["keep_columns"]
                new_cells = []
                for ci, cell in enumerate(cells):
                    new_cells.append(cell if ci in keep else r.common(cell, events, ctx, "prose", ffi_scope=ffi_scope))
                lead = line[: len(line) - len(line.lstrip())]
                new = lead + "|" + "|".join(new_cells) + ("|" if line.rstrip().endswith("|") else "")
                exempt_reason.append(None)
                out.append(new)
                continue
            else:
                new = r.common(line, events, ctx, "prose", ffi_scope=ffi_scope)
        exempt_reason.append(None)
        out.append(new)
    if cls == "c" and path.endswith(".h"):
        out = realign_c(lines, out)
    scan_residue(r, path, out, residue, cls, exempt_reason, rules)
    return "\n".join(out)


def open_paren(line: str) -> int:
    """Column of the innermost parenthesis a line leaves open."""
    stack = []
    for i, ch in enumerate(line):
        if ch == "(":
            stack.append(i)
        elif ch == ")" and stack:
            stack.pop()
    return stack[-1]


def realign_c(old: list[str], new: list[str]) -> list[str]:
    """A header generated by cbindgen aligns a declaration's continuation lines one column after
    its opening parenthesis; a longer name moves that column, so move the continuations too (the
    header then equals what cbindgen generates from the renamed sources)."""
    out = list(new)
    i = 0
    while i < len(old):
        o, n = old[i], out[i]
        if o != n and o.count("(") > o.count(")"):
            col_old, col_new = open_paren(o) + 1, open_paren(n) + 1
            depth = o.count("(") - o.count(")")
            j = i + 1
            while depth > 0 and j < len(old):
                lead = len(old[j]) - len(old[j].lstrip(" "))
                if lead == col_old and col_new != col_old:
                    out[j] = " " * col_new + out[j].lstrip(" ")
                depth += old[j].count("(") - old[j].count(")")
                j += 1
            i = j
            continue
        i += 1
    return out


def exceptions_for(path: str):
    return [(re.compile(b), re.compile(a), why) for pat, b, a, why in EXCEPTIONS if glob_re(pat).match(path)]


def scan_residue(r: Renamer, path, lines, residue, cls, exempt_reason=None, rules=None):
    section = ""
    exceptions = exceptions_for(path)
    for i, line in enumerate(lines):
        hm = re.match(r"^#{1,6}\s+(.*)$", line)
        if hm and path.endswith(".md"):
            section = hm.group(1).strip()
        spans = Renamer.masks(line)
        for m in RESIDUE_RE.finditer(line):
            start = m.start()
            left = re.search(r"[A-Za-z0-9_-]*$", line[:start]).group(0)
            token = (left + re.match(r"[A-Za-z0-9_-]*", line[start:]).group(0)).strip("-_")
            excepted = next((w for b, a, w in exceptions if b.search(line[:start]) and a.match(line[m.end() :])), None)
            if exempt_reason and i < len(exempt_reason) and exempt_reason[i]:
                why = exempt_reason[i]
            elif excepted:
                why = excepted
            elif Renamer.in_masks(start, spans):
                why = "URL of another project (upstream repository, crates.io / docs.rs pages of upstream's crates)"
            elif rules and any(section.startswith(k) for k in rules) and split_cells(line) is not None:
                why = "table cell about upstream (FORK.md)"
            elif UPSTREAM_BEFORE.search(line[:start]):
                why = "statement about upstream (`upstream's rtc-...`)"
            elif token == "webrtc-rs-rtc":
                why = "UNEXPECTED: old repository name"
            elif token == OLD_ROOT:
                nxt = line[m.end() : m.end() + 1]
                why = "the word `rtc` in prose, identifiers, strings or keys (not a crate path)"
                if nxt == "." and re.match(r"rtc\.test\b", line[start:]):
                    why = "test-environment realm `rtc.test` (not a crate name)"
            elif token in r.pkg or token in r.lib:
                why = "UNEXPECTED: old crate name left (rule gap)"
            else:
                why = "name that is not a crate name (identifier, image, package or directory: rtc_pc, rtc-testenv, ...)"
            residue.append(Residue(path, i + 1, why, line.strip(), token))


