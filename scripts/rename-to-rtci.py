@dataclass
class Event:
    path: str
    line: int
    category: str
    old: str
    new: str


@dataclass
class Residue:
    path: str
    line: int
    reason: str
    text: str
    token: str = ""


URL_RE = re.compile(r"https?://[^\s<>\"'`)\]]+")
UPSTREAM_BEFORE = re.compile(r"(?i)\b(?:upstream(?:'s)?|webrtc-rs(?:'s)?)\s*[`\[(\"']*\s*$")
RESIDUE_RE = re.compile(r"(?<![A-Za-z0-9])rtc(?![a-z0-9])|(?<![A-Za-z0-9_.-])webrtc-rs-rtc(?![A-Za-z0-9_-])")


def alt(names) -> str:
    return "|".join(re.escape(n) for n in sorted(set(names), key=lambda s: (-len(s), s)))


class Renamer:
    def __init__(self, crates: list[Crate], ffi_symbols: set[str], headers: dict[str, str], renamed_state: bool):
        self.crates = crates
        self.pkg = {c.old: c.new for c in crates}
        self.pkg[OLD_ROOT] = NEW_ROOT
        self.lib = {c.old_lib: c.new_lib for c in crates if c.old_lib != c.new_lib}
        self.lib[OLD_ROOT] = NEW_ROOT
        hyphen = [n for n in self.pkg if n != OLD_ROOT]
        libs = [n for n in self.lib if n != OLD_ROOT]
        self.old_names = set(self.pkg) | set(self.lib)
        self.renamed_state = renamed_state
        never = r"(?!x)x"
        # A crate name, also as the start of a name made from it (rtc-ffi-release, rtc-dtls-fuzz).
        self.pkg_re = re.compile(r"(?<![A-Za-z0-9_.@-])(" + (alt(hyphen) or never) + r")(?![A-Za-z0-9_])")
        # A library file name: librtc_ffi.so, librtc_ffi.a, librtc.rlib.
        self.libfile_re = re.compile(r"(?<![A-Za-z0-9_])lib(" + alt(self.lib) + r")(?![A-Za-z0-9_])")
        self.lib_re = re.compile(r"(?<![A-Za-z0-9_$])(" + (alt(libs) or never) + r")(?![A-Za-z0-9_])")
        self.lib_prefix_re = re.compile(r"(?<![A-Za-z0-9_$])(" + (alt(libs) or never) + r")(?=_[A-Za-z0-9])")
        self.ffi = set(ffi_symbols)
        self.ffi_re = re.compile(r"(?<![A-Za-z0-9_])(" + (alt(self.ffi) or never) + r")(?![A-Za-z0-9_])")
        # Header files renamed with their crate (old file name -> new).
        self.headers = headers
        self.header_re = re.compile(r"(?<![A-Za-z0-9_.-])(" + (alt(headers) or never) + r")(?![A-Za-z0-9_])")
        self.ffi_crates = [c for c in crates if c.kinds & {"cdylib", "staticlib"}]
        self.ffi_dirs = [c.manifest.rsplit("/", 1)[0] for c in self.ffi_crates if "/" in c.manifest]
        ffi_names = [c.old for c in self.ffi_crates] + [c.new for c in self.ffi_crates]
        ffi_names += [c.old_lib for c in self.ffi_crates] + [c.new_lib for c in self.ffi_crates]
        ffi_names += list(headers) + list(headers.values())
        # Upper-case names made from the FFI library's name (RTC_FFI_LIB, RTC_FFI_TARGET).
        ffi_upper = [c.old_lib.upper() for c in self.ffi_crates if c.old_lib.startswith(OLD_ROOT + "_")]
        self.ffi_upper_re = re.compile(r"(?<![A-Za-z0-9_])(" + (alt(ffi_upper) or never) + r")(?![A-Za-z0-9])")
        # Families of exported names: rtc_pc_*, rtc_driven_*, RTC_ERR_*.
        self.ffi_glob_re = re.compile(r"(?<![A-Za-z0-9_])(rtc|RTC)(_[A-Za-z0-9_]*\*)")
        self.ffi_scope_re = re.compile(r"(?<![A-Za-z0-9_])(" + (alt(ffi_names) or never) + r")(?![A-Za-z0-9_])")

    # -- helpers ----------------------------------------------------------------------------

    @staticmethod
    def masks(line: str) -> list[tuple[int, int]]:
        spans = []
        for m in URL_RE.finditer(line):
            url = m.group(0)
            if f"github.com/{NEW_REPO}" in url or f"githubusercontent.com/{NEW_REPO}" in url:
                continue
            spans.append((m.start(), m.end()))
        return spans

    @staticmethod
    def in_masks(pos: int, spans) -> bool:
        return any(a <= pos < b for a, b in spans)

    def sub(self, rx, line, repl, category, events, ctx, guard=True, exceptions=()):
        spans = self.masks(line)

        def cb(m):
            start = m.start(m.lastindex or 0) if m.lastindex else m.start()
            if guard and self.in_masks(start, spans):
                return m.group(0)
            before = line[:start]
            if guard and UPSTREAM_BEFORE.search(before):
                return m.group(0)
            after = line[m.end(m.lastindex) if m.lastindex else m.end() :]
            for rxb, rxa, _reason in exceptions:
                if rxb.search(before) and rxa.match(after):
                    return m.group(0)
            new = repl(m)
            if new != m.group(0):
                events.append(Event(ctx[0], ctx[1], category, m.group(0), new))
            return new

        return rx.sub(cb, line)

    # -- the rule sets ----------------------------------------------------------------------

    def common(self, line, events, ctx, cls, comment=False, ffi_scope=False, exceptions=()):
        """Rules for every text file: names that can only be ours."""
        # Our repository.
        line = self.sub(re.compile(re.escape(OLD_REPO)), line, lambda m: NEW_REPO, "repository", events, ctx, guard=False)
        line = self.sub(
            re.compile(r"(?<![A-Za-z0-9_.-])webrtc-rs-rtc(?![A-Za-z0-9_-])"), line, lambda m: NEW_ROOT, "repository", events, ctx
        )
        # Hyphenated crate names and crate directories.
        line = self.sub(self.pkg_re, line, lambda m: self.pkg[m.group(1)], "crate-name", events, ctx)
        # Library paths (rtc_dtls::, use rtc_ice, RUST_LOG=rtc_mdns=trace, ...).
        line = self.sub(self.lib_re, line, lambda m: self.lib[m.group(1)], "library-path", events, ctx)
        # Globs over the crate directories (rtc-*/src, rtc-*/Cargo.toml).
        line = self.sub(re.compile(r"(?<![A-Za-z0-9_.@-])rtc([-_])\*"), line, lambda m: NEW_ROOT + m.group(1) + "*", "glob", events, ctx)
        # The root crate's paths: rtc::x, ::rtc::x (not foo::rtc::, not webrtc::).
        line = self.sub(
            re.compile(r"(?<![A-Za-z0-9_$/-])(?<![A-Za-z0-9_]\.)(?<![A-Za-z0-9_>]::)(rtc)(?=::)"), line, lambda m: NEW_ROOT, "root-crate-path", events, ctx
        )
        # `rtc` as a code span: the crate.
        line = self.sub(re.compile(r"(?<=`)(rtc)(?=`)"), line, lambda m: NEW_ROOT, "code-span", events, ctx)
        # cargo flags naming the root crate: -p rtc, --package rtc, --features rtc/x.
        line = self.sub(
            re.compile(r"((?:^|[\s\"'`(])(?:-p|--package|--crate|--exclude)[ =])(rtc)(?![A-Za-z0-9_./-])"),
            line,
            lambda m: m.group(1) + NEW_ROOT,
            "cargo-flag",
            events,
            ctx,
        )
        line = self.sub(
            re.compile(r"((?:--features|-F)[ =][\"']?(?:[A-Za-z0-9_/,-]+,)?)(rtc)(?=/)"),
            line,
            lambda m: m.group(1) + NEW_ROOT,
            "cargo-flag",
            events,
            ctx,
        )
        # The C header, renamed with its crate.
        line = self.sub(self.header_re, line, lambda m: self.headers[m.group(1)], "c-header", events, ctx)
        line = self.sub(self.libfile_re, line, lambda m: "lib" + self.lib[m.group(1)], "library-file", events, ctx)
        if ffi_scope:
            line = self.sub(
                self.ffi_glob_re,
                line,
                lambda m: (NEW_ROOT if m.group(1) == OLD_ROOT else NEW_ROOT.upper()) + m.group(2)
                if any(f.startswith(m.group(1) + m.group(2)[:-1]) for f in self.ffi)
                else m.group(0),
                "c-symbol",
                events,
                ctx,
            )
            line = self.sub(self.ffi_upper_re, line, lambda m: NEW_ROOT.upper() + m.group(1)[len(OLD_ROOT) :], "c-symbol", events, ctx)
            line = self.sub(self.ffi_re, line, lambda m: new_of(m.group(1)) if m.group(1).startswith(OLD_ROOT) else NEW_ROOT.upper() + m.group(1)[3:], "c-symbol", events, ctx)
        return line

    def rust(self, line, events, ctx, ffi_scope=False):
        line = self.sub(re.compile(r"(\b(?:use|extern\s+crate)\s+)(rtc)(?=\s*(?:;|\bas\b))"), line, lambda m: m.group(1) + NEW_ROOT, "root-crate-path", events, ctx)
        if re.search(r"CARGO_(?:PKG|CRATE)_NAME", line):
            line = self.sub(re.compile(r"(\")(rtc)(?=\")"), line, lambda m: m.group(1) + NEW_ROOT, "quoted-name", events, ctx)
        return self.common(line, events, ctx, "rust", ffi_scope=ffi_scope)

    def code(self, line, events, ctx, path, shell=False, ffi_scope=False, exceptions=()):
        """YAML, Python, shell, TOML other than Cargo.toml: code part and comment part."""
        code, comment = split_comment(line)
        code = self.common(code, events, ctx, "code", ffi_scope=ffi_scope, exceptions=exceptions)
        code = self.sub(re.compile(r"([\"'])(rtc)(?=\1)"), code, lambda m: m.group(1) + NEW_ROOT, "quoted-name", events, ctx, exceptions=exceptions)
        code = self.sub(re.compile(r"([\"'])(rtc)(?=[-_]\1)"), code, lambda m: m.group(1) + NEW_ROOT, "quoted-name", events, ctx, exceptions=exceptions)
        if shell:
            code = self.sub(
                re.compile(r"(?<![A-Za-z0-9_./$:=@-])(rtc)(?![A-Za-z0-9_./:@-])"), code, lambda m: NEW_ROOT, "shell-word", events, ctx, exceptions=exceptions
            )
        if path.startswith(".github/workflows/"):
            code = self.workflow_job_ids(code, events, ctx)
        if path == "cliff.toml":
            code = self.sub(
                re.compile(re.escape(UPSTREAM_REPO_URL) + r"(?=/commit/)"), code, lambda m: f"https://github.com/{NEW_REPO}", "cliff-link", events, ctx, guard=False
            )
        if comment:
            comment = self.common(comment, events, ctx, "prose", ffi_scope=ffi_scope)
        return code + comment

    def workflow_job_ids(self, line, events, ctx):
        # Job ids beginning with a library name (rtc_crypto_provider_matrix:) and their `needs:`.
        return self.sub(self.lib_prefix_re, line, lambda m: self.lib[m.group(1)], "workflow-job-id", events, ctx)

    def plain(self, line, events, ctx, ffi_scope=False):
        """JSON, JavaScript, configuration: only names that can only be ours."""
        return self.common(line, events, ctx, "plain", ffi_scope=ffi_scope)

    def toml_snippet(self, line, events, ctx):
        """A TOML line inside a Markdown code block: a dependency on the root crate."""
        m = re.match(r'^(\s*)(rtc|' + (alt(n for n in self.pkg if n != OLD_ROOT) or "(?!x)x") + r')(\s*=\s*)(.*)$', line)
        if m:
            new_key = self.pkg[m.group(2)]
            rest = m.group(4)
            rest2 = re.sub(r'^"\d+(?:\.\d+)*(?:\+[^"]*)?"', '"0.1"', rest)
            rest2 = re.sub(r'(\bversion\s*=\s*)"[^"]*"', r'\g<1>"0.1"', rest2)
            events.append(Event(ctx[0], ctx[1], "doc-dependency", m.group(2), new_key))
            if rest2 != rest:
                events.append(Event(ctx[0], ctx[1], "version", rest, rest2))
            line = m.group(1) + new_key + m.group(3) + rest2
        line = re.sub(r"^(\s*\[(?:[a-z-]+\.)*(?:dependencies|dev-dependencies|build-dependencies)\.)(rtc)(\])", lambda mm: mm.group(1) + NEW_ROOT + mm.group(3), line)
        return self.common(line, events, ctx, "prose")


def split_comment(line: str) -> tuple[str, str]:
    """Split `code # comment` (YAML, Python, shell, TOML) outside quotes."""
    quote = None
    prev = " "
    for i, ch in enumerate(line):
        if quote:
            if ch == quote and prev != "\\":
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "#" and (i == 0 or prev.isspace()):
            return line[:i], line[i:]
        prev = ch
    return line, ""


