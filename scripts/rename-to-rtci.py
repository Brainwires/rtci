def glob_re(pattern: str) -> re.Pattern:
    out = ""
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif pattern.startswith("**", i):
            out += ".*"
            i += 2
        elif pattern[i] == "*":
            out += "[^/]*"
            i += 1
        else:
            out += re.escape(pattern[i])
            i += 1
    return re.compile(out + r"\Z")


EXCLUDED_RES = [(glob_re(p), reason) for p, reason in EXCLUDED_PATHS]


def excluded(path: str) -> str | None:
    for rx, reason in EXCLUDED_RES:
        if rx.match(path):
            return reason
    return None


def file_class(path: str) -> str | None:
    name = path.rsplit("/", 1)[-1]
    if name == "Cargo.toml":
        return "cargo"
    if name == "Dockerfile" or name.endswith(".Dockerfile"):
        return "shell"
    if name in ("Makefile", "justfile"):
        return "shell"
    suffix = "." + name.rsplit(".", 1)[-1] if "." in name else ""
    return TEXT_SUFFIX_CLASS.get(suffix)


