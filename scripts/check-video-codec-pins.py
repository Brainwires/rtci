#!/usr/bin/env python3
"""The VP8 crates are the reviewed bytes, and nothing else (docs/video-pipeline.md 4.7).

``vp8-decoder`` and ``vp8-encoder`` are weeks old, from one publisher, and parse what a remote
peer sends. They are pinned to an exact version in ``rtc-video/Cargo.toml``, and ``Cargo.lock``
is not committed at the root of this repository, so the checksum of what a build downloads is
recorded nowhere in the tree. This script closes that gap. It fails when:

* ``rtc-video/Cargo.toml`` asks for either crate with anything but the exact version below;
* a ``Cargo.lock`` (the workspace's, generated by any build or by ``cargo generate-lockfile``;
  it lists optional dependencies whether or not their feature is on) holds either crate at
  another version or with another checksum than the one the review downloaded and compared
  with the repository's tagged commit.

Moving the pin is a change to this file, with the review of the new version (diff of the
published crate against its tagged commit, ``unsafe`` and build-time code, the conformance and
fuzz runs of docs/video-pipeline.md 4.6) in the same change.

Usage: ``python3 scripts/check-video-codec-pins.py [path/to/Cargo.lock]`` (default: the
workspace's ``Cargo.lock``; when it does not exist only the manifest is checked).
"""

from __future__ import annotations

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Reviewed 2026-11-24: the .crate files from static.crates.io matched these SHA-256 sums (the
# index's) and, file for file, the repository AlakazamLabs/vp8 at 28844d61 (tags
# vp8-decoder-v0.1.3, vp8-encoder-v0.1.3).
PINNED = {
    "vp8-decoder": ("0.1.3", "7011d3a4631e53d8384affbae3a64d40434740d546ec618e31080eb433ebe3e0"),
    "vp8-encoder": ("0.1.3", "f3a93dc20d039e03e74d62120ecd3783a47882bb930c1481498b7d4843ed0dc4"),
}
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"


def check_manifest(errors: list[str]) -> None:
    path = os.path.join(ROOT, "rtc-video", "Cargo.toml")
    text = open(path, encoding="utf-8").read()
    for name, (version, _) in PINNED.items():
        m = re.search(rf'^{re.escape(name)}\s*=\s*\{{[^}}]*version\s*=\s*"([^"]+)"', text, re.M)
        if not m:
            errors.append(f"rtc-video/Cargo.toml: no `{name} = {{ version = ... }}` entry")
        elif m.group(1) != f"={version}":
            errors.append(
                f'rtc-video/Cargo.toml: {name} asks for "{m.group(1)}", not the reviewed "={version}"'
            )


def check_lock(path: str, errors: list[str]) -> int:
    text = open(path, encoding="utf-8").read()
    seen = 0
    for block in text.split("[[package]]")[1:]:
        fields = dict(re.findall(r'^(\w+) = "([^"]*)"', block, re.M))
        name = fields.get("name")
        if name not in PINNED:
            continue
        seen += 1
        version, checksum = PINNED[name]
        if fields.get("version") != version:
            errors.append(f"{path}: {name} {fields.get('version')}, reviewed is {version}")
        if fields.get("source") != REGISTRY:
            errors.append(f"{path}: {name} from {fields.get('source')}, not crates.io")
        if fields.get("checksum") != checksum:
            errors.append(f"{path}: {name} checksum {fields.get('checksum')}, reviewed is {checksum}")
    return seen


def main() -> int:
    errors: list[str] = []
    check_manifest(errors)
    lock = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "Cargo.lock")
    if os.path.exists(lock):
        seen = check_lock(lock, errors)
        note = f"{seen} pinned crate(s) in {os.path.relpath(lock, ROOT)}"
    else:
        note = "no Cargo.lock: manifest only"
    for e in errors:
        print(f"error: {e}")
    if errors:
        return 1
    print(f"video codec pins: ok ({note})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
