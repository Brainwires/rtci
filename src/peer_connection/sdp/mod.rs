pub(crate) struct AddTransceiverSdpParams {
    should_add_candidates: bool,
    mid_value: String,
    dtls_role: ConnectionRole,
    ice_gathering_state: RTCIceGatheringState,
    ignore_rid_pause_for_recv: bool,
    write_ssrc_attributes_for_simulcast: bool,
    /// An offer (initial or subsequent) rather than an answer.
    is_offer: bool,
}

impl RTCPeerConnection {
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn add_transceiver_sdp(
        mut d: SessionDescription,
        dtls_fingerprints: &[RTCDtlsFingerprint],
        media_engine: &MediaEngine,
        transceivers: &mut [RTCRtpTransceiverInternal],
        ice_params: &RTCIceParameters,
        candidates: &[RTCIceCandidate],
        media_section: &MediaSection,
        params: AddTransceiverSdpParams,
    ) -> Result<(SessionDescription, bool)> {
        let (
            should_add_candidates,
            mid_value,
            dtls_role,
            ice_gathering_state,
            ignore_rid_pause_for_recv,
            write_ssrc_attributes_for_simulcast,
            is_offer,
        ) = (
            params.should_add_candidates,
            params.mid_value,
            params.dtls_role,
            params.ice_gathering_state,
            params.ignore_rid_pause_for_recv,
            params.write_ssrc_attributes_for_simulcast,
            params.is_offer,
        );

        let transceiver = &mut transceivers[media_section.transceiver_index];
        let mut media =
            MediaDescription::new_jsep_media_description(transceiver.kind().to_string(), vec![])
                .with_value_attribute(ATTR_KEY_CONNECTION_SETUP.to_owned(), dtls_role.to_string())
                .with_value_attribute(ATTR_KEY_MID.to_owned(), mid_value.clone())
                .with_ice_credentials(
                    ice_params.username_fragment.clone(),
                    ice_params.password.clone(),
                )
                .with_property_attribute(ATTR_KEY_RTCPMUX.to_owned())
                .with_property_attribute(ATTR_KEY_RTCPRSIZE.to_owned());

        let codecs = transceiver.get_codecs(media_engine);
        // Which repair flows the section has a format for: a sender's RTX / FlexFEC SSRCs are
        // described only then (codec preferences may leave either out). The FEC flow is the
        // FlexFEC draft-03 coder's (`video/flexfec-03`, matched exactly as the sender's
        // `find_fec_payload_type` does): RFC 8627's `video/flexfec` is another wire format.
        let repair_flows = RepairFlows {
            rtx: codecs.iter().any(|c| repair_family(&c.rtp_codec) == "rtx"),
            fec: codecs
                .iter()
                .any(|c| is_flexfec03_mime_type(&c.rtp_codec.mime_type)),
        };
        for codec in &codecs {
            let name = codec
                .rtp_codec
                .mime_type
                .trim_start_matches("audio/")
                .trim_start_matches("video/")
                .trim_start_matches("application/")
                .to_owned();
            media = media.with_codec(
                codec.payload_type,
                name,
                codec.rtp_codec.clock_rate,
                codec.rtp_codec.channels,
                codec.rtp_codec.sdp_fmtp_line.clone(),
            );

            for feedback in &codec.rtp_codec.rtcp_feedback {
                media = media.with_value_attribute(
                    "rtcp-fb".to_owned(),
                    if feedback.parameter.is_empty() {
                        format!("{} {}", codec.payload_type, feedback.typ)
                    } else {
                        format!(
                            "{} {} {}",
                            codec.payload_type, feedback.typ, feedback.parameter
                        )
                    },
                );
            }
        }
        if codecs.is_empty() {
            // If we are sender and have no codecs throw an error early
            if transceiver.sender().is_some() {
                return Err(Error::ErrSenderWithNoCodecs);
            }

            // Explicitly reject track if we don't have the codec
            // RFC 9429 Section 5.3.1: Set port=0 to reject, further processing can be skipped
            // However, mid attribute is still needed for offer/answer correlation with BUNDLE
            d = d.with_media(
                MediaDescription {
                    media_name: MediaName {
                        media: transceiver.kind().to_string(),
                        port: RangedPort {
                            value: 0,
                            range: None,
                        },
                        protos: vec![
                            "UDP".to_owned(),
                            "TLS".to_owned(),
                            "RTP".to_owned(),
                            "SAVPF".to_owned(),
                        ],
                        formats: vec!["0".to_owned()],
                    },
                    media_title: None,
                    // We need to include connection information even if we're rejecting a track, otherwise Firefox will fail to
                    // parse the SDP with an error like:
                    // SIPCC Failed to parse SDP: SDP Parse Error on line 50:  c= connection line not specified for every media level, validation failed.
                    // In addition this makes our SDP compliant with RFC 4566 Section 5.7: https://datatracker.ietf.org/doc/html/rfc4566#section-5.7
                    connection_information: Some(ConnectionInformation {
                        network_type: "IN".to_owned(),
                        address_type: "IP4".to_owned(),
                        address: Some(Address {
                            address: "0.0.0.0".to_owned(),
                            ttl: None,
                            range: None,
                        }),
                    }),
                    bandwidth: vec![],
                    encryption_key: None,
                    attributes: vec![],
                }
                .with_value_attribute(ATTR_KEY_MID.to_owned(), mid_value),
            );
            return Ok((d, false));
        }

        let parameters =
            media_engine.get_rtp_parameters_by_kind(transceiver.kind(), transceiver.direction());
        let to_negotiate = transceiver.header_extensions_to_negotiate();
        let mut written: Vec<(u16, String)> = vec![];
        for rtp_extension in &parameters.header_extensions {
            if let Some(uris) = to_negotiate
                && !uris.contains(&rtp_extension.uri)
            {
                continue;
            }
            let id = if media_section.match_extensions.is_empty() {
                rtp_extension.id
            } else if let Some(id) = media_section.match_extensions.get(&rtp_extension.uri) {
                *id
            } else {
                continue;
            };
            written.push((id, rtp_extension.uri.clone()));
        }
        if is_offer && let Some(uris) = to_negotiate {
            for (id, uri) in reoffered_header_extensions(
                media_engine,
                transceiver.kind(),
                transceiver.direction(),
                uris,
                &written,
            ) {
                written.push((id, uri));
            }
        }
        for (id, uri) in &written {
            let ext_url = Url::parse(uri.as_str())?;
            media = media.with_extmap(sdp::extmap::ExtMap {
                value: *id,
                uri: Some(ext_url),
                ..Default::default()
            });
        }

        let mut recv_sc_list: Vec<String> = vec![];
        let mut send_sc_list: Vec<String> = vec![];
        if !media_section.rid_map.is_empty() {
            for rid in &media_section.rid_map {
                let rid_syntax = match rid.direction {
                    SimulcastDirection::Send => {
                        // If Send rid, then reply with a recv rid
                        if rid.paused {
                            recv_sc_list.push(format!("~{}", rid.id));
                        } else {
                            recv_sc_list.push(rid.id.to_owned());
                        }
                        format!("{} recv", rid.id)
                    }
                    SimulcastDirection::Recv => {
                        // If Recv rid, then reply with a send rid
                        if rid.paused && !ignore_rid_pause_for_recv {
                            send_sc_list.push(format!("~{}", rid.id));
                        } else {
                            send_sc_list.push(rid.id.to_owned());
                        }
                        format!("{} send", rid.id)
                    }
                };
                media = media.with_value_attribute(SDP_ATTRIBUTE_RID.to_owned(), rid_syntax);
            }
        }

        media = {
            // When the remote description requested simulcast reception, the
            // rid loop above already emitted one `a=rid:<id> send` line per
            // offered rid (honoring pause state and the offered preference
            // order) and collected them into `send_sc_list`. In that case the
            // sender must not describe its encodings a second time: doing so
            // duplicated every `a=rid:<id> send` line and produced a second
            // `send` list in the simulcast attribute (`a=simulcast:send f;h;q
            // send f;h;q`), which is invalid per the RFC 8853 Section 5.1 ABNF
            // (at most one list per direction) and rejected by WebKit with
            // "Malformed simulcast line".
            let (media, send_rids) = RTCPeerConnection::add_sender_sdp(
                media,
                media_engine,
                transceiver,
                write_ssrc_attributes_for_simulcast,
                send_sc_list.is_empty(),
                repair_flows,
            );

            // Simulcast
            let mut sc_attr = vec![];
            if !recv_sc_list.is_empty() {
                sc_attr.push(format!("recv {}", recv_sc_list.join(";")));
            }
            if !send_sc_list.is_empty() {
                sc_attr.push(format!("send {}", send_sc_list.join(";")));
            }
            if !send_rids.is_empty() {
                sc_attr.push(format!("send {}", send_rids.join(";")));
            }
            if !sc_attr.is_empty() {
                media.with_value_attribute(SDP_ATTRIBUTE_SIMULCAST.to_owned(), sc_attr.join(" "))
            } else {
                media
            }
        };

        // An answer's direction is the transceiver's [[Direction]] intersected with the reverse
        // of the offered one (RFC 9429 section 5.3.1, RFC 3264 section 6.1); an offer states
        // [[Direction]] itself.
        let direction = media_section
            .answer_direction
            .unwrap_or_else(|| transceiver.direction());
        media = media.with_property_attribute(direction.to_string());

        for fingerprint in dtls_fingerprints {
            media = media.with_fingerprint(
                fingerprint.algorithm.to_owned(),
                fingerprint.value.to_uppercase(),
            );
        }

        if should_add_candidates {
            media = add_candidates_to_media_descriptions(candidates, media, ice_gathering_state)?;
        }

        Ok((d.with_media(media), true))
    }

    /// `write_rid_attributes` is false when the media section's rid map has
    /// already emitted the `a=rid:<id> send` lines for this section, in which
    /// case the sender's encodings must not be described a second time.
    fn add_sender_sdp(
        mut media: MediaDescription,
        media_engine: &MediaEngine,
        transceiver: &mut RTCRtpTransceiverInternal,
        write_ssrc_attributes_for_simulcast: bool,
        write_rid_attributes: bool,
        repair_flows: RepairFlows,
    ) -> (MediaDescription, Vec<RtpStreamId>) {
        let mut send_rids = vec![];

        if let Some(sender) = transceiver.sender_mut() {
            let (encodings, track) = (
                sender.get_parameters(media_engine).encodings.clone(),
                sender.track(),
            );

            let is_simulcast = encodings.len() > 1
                && encodings
                    .iter()
                    .all(|encoding| !encoding.rtp_coding_parameters.rid.is_empty());

            // One `a=msid` line per MediaStream the sender is associated with (RFC 9429,
            // Section 5.2.1); a sender in no stream writes the stream id `-` (its track's own
            // stream id, which the application sets to `-` for that).
            let track_id = track.track_id().to_string();
            let mut stream_ids: Vec<String> = vec![];
            for stream_id in sender.streams() {
                if !stream_ids.contains(stream_id) {
                    stream_ids.push(stream_id.clone());
                }
            }
            if stream_ids.is_empty() {
                stream_ids.push(track.stream_id().to_string());
            }
            for stream_id in stream_ids {
                media = media.with_property_attribute(format!("msid:{} {}", stream_id, track_id));
            }

            if write_ssrc_attributes_for_simulcast || !is_simulcast {
                for encoding in &encodings {
                    if let Some(&ssrc) = encoding.rtp_coding_parameters.ssrc.as_ref() {
                        let rtx_flow = encoding
                            .rtp_coding_parameters
                            .rtx
                            .as_ref()
                            .filter(|_| repair_flows.rtx);
                        let fec_flow = encoding
                            .rtp_coding_parameters
                            .fec
                            .as_ref()
                            .filter(|_| repair_flows.fec);
                        if let Some(rtx) = rtx_flow {
                            media = media.with_value_attribute(
                                ATTR_KEY_SSRC_GROUP.to_owned(),
                                format!(
                                    "{} {} {}",
                                    SEMANTIC_TOKEN_FLOW_IDENTIFICATION, ssrc, rtx.ssrc
                                ),
                            );
                        }

                        if let Some(fec) = fec_flow {
                            // `FEC-FR` (RFC 5956), not the older `FEC` semantic of RFC 4756:
                            // FlexFEC repair flows are grouped under the FEC framework, and
                            // `parse_media_section` below only recognises `FEC-FR`, so writing
                            // `FEC` here produced an offer this crate could not parse back.
                            media = media.with_value_attribute(
                                ATTR_KEY_SSRC_GROUP.to_owned(),
                                format!(
                                    "{} {} {}",
                                    SEMANTIC_TOKEN_FORWARD_ERROR_CORRECTION_FRAMEWORK,
                                    ssrc,
                                    fec.ssrc
                                ),
                            );
                        }

                        media = with_source_attributes(media, ssrc, track);
                        if let Some(rtx) = rtx_flow {
                            media = with_source_attributes(media, rtx.ssrc, track);
                        }
                        if let Some(fec) = fec_flow {
                            media = with_source_attributes(media, fec.ssrc, track);
                        }
                    }
                }
            }

            if is_simulcast && write_rid_attributes {
                for encoding in &encodings {
                    media = media.with_value_attribute(
                        SDP_ATTRIBUTE_RID.to_owned(),
                        format!("{} send", encoding.rtp_coding_parameters.rid),
                    );
                    // RFC 8853, Section 5.3: an inactive encoding's rid is paused.
                    if encoding.active {
                        send_rids.push(encoding.rtp_coding_parameters.rid.to_string());
                    } else {
                        send_rids.push(format!("~{}", encoding.rtp_coding_parameters.rid));
                    }
                }
            }
        }

        (media, send_rids)
    }
}

/// The source attributes of one of a sender's SSRCs (RFC 5576 section 4.1): `cname` (section
/// 6.1) and `msid` (RFC 8830 appendix A, registered as a source attribute). The Plan B
/// `mslabel` and `label` attributes are not written: RFC 5576 section 4.1 has source
/// attributes registered with IANA, and neither is.
fn with_source_attributes(
    media: MediaDescription,
    ssrc: SSRC,
    track: &MediaStreamTrack,
) -> MediaDescription {
    media
        .with_value_attribute(
            ATTR_KEY_SSRC.to_owned(),
            format!("{ssrc} cname:{}", track.stream_id()),
        )
        .with_value_attribute(
            ATTR_KEY_SSRC.to_owned(),
            format!("{ssrc} msid:{} {}", track.stream_id(), track.track_id()),
        )
}

/// Whether an m-section has a format for a sender's RTX (RFC 4588) and FlexFEC
/// (draft-ietf-payload-flexible-fec-scheme-03, `video/flexfec-03`) flows.
#[derive(Debug, Copy, Clone)]
pub(crate) struct RepairFlows {
    pub(crate) rtx: bool,
    pub(crate) fec: bool,
}

#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub(crate) enum SimulcastDirection {
    Send,
    Recv,
}

impl TryFrom<&str> for SimulcastDirection {
    type Error = Error;
    fn try_from(value: &str) -> std::result::Result<Self, Self::Error> {
        match value.to_lowercase().as_str() {
            "send" => Ok(SimulcastDirection::Send),
            "recv" => Ok(SimulcastDirection::Recv),
            _ => Err(Error::SimulcastRidParseErrorUnknownDirection),
        }
    }
}

#[derive(Clone, Debug)]
pub(crate) struct SimulcastRid {
    pub(crate) id: String,
    pub(crate) direction: SimulcastDirection,
    pub(crate) params: String,
    pub(crate) paused: bool,
}

impl TryFrom<&String> for SimulcastRid {
    type Error = Error;
    fn try_from(value: &String) -> std::result::Result<Self, Self::Error> {
        let mut split = value.split(' ');
        let id = split
            .next()
            .ok_or(Error::SimulcastRidParseErrorSyntaxIdDirSplit)?
            .to_owned();
        let direction = SimulcastDirection::try_from(
            split
                .next()
                .ok_or(Error::SimulcastRidParseErrorSyntaxIdDirSplit)?,
        )?;
        let params = split.collect();

        Ok(Self {
            id,
            direction,
            params,
            paused: false,
        })
    }
}

/// What a generated description does about BUNDLE (RFC 9143).
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum BundleMode {
    /// An offer: every media section that is not rejected is in the one BUNDLE group.
    Offer,
    /// An answer to an offer with this BUNDLE group (its identification-tags, in the offer's
    /// order), or with none. With a group, the answer's group holds the accepted sections of
    /// it, in its order (RFC 9143 section 7.3.1: the answerer-tagged section is the first the
    /// offer suggested that is accepted), and a section outside it, which would need a
    /// transport of its own, is rejected. With none, no group is written and no section is
    /// rejected for it (RFC 9143 section 7.3: "The answerer MUST NOT include a BUNDLE group in
    /// the answer unless the offer contained one"; RFC 9429 section 5.3.1).
    Answer(Option<Vec<String>>),
}

impl BundleMode {
    /// The mode of the answer to `offer`: its first non-empty `a=group:BUNDLE` (an
    /// `a=group` line of other semantics, such as LS, is not one).
    pub(crate) fn answering(offer: &SessionDescription) -> Self {
        BundleMode::Answer(
            bundle_groups(offer)
                .into_iter()
                .find(|group| !group.is_empty())
                .map(|group| group.into_iter().map(str::to_owned).collect()),
        )
    }
}

#[derive(Default)]
pub(crate) struct MediaSection {
    pub(crate) mid: String,
    pub(crate) transceiver_index: usize,
    pub(crate) data: bool,
    /// RFC 8829 §5.3.1: this m-line should be reflected as rejected (port=0) in the answer.
    /// Used when the remote offer contains a rejected m-line (no direction attribute / port=0).
    pub(crate) rejected: bool,
    /// Media kind string ("video", "audio", or "application") — only meaningful when `rejected` is true.
    pub(crate) rejected_kind: String,
    /// A rejected m-line for a stopped transceiver: it also says `a=inactive` (W3C `stop()`,
    /// RFC 9429 Section 5.2.2), as browsers write it.
    pub(crate) stopped: bool,
    /// For a rejected m-section of a media type this endpoint doesn't know:
    /// the protocol and formats to reproduce (the offer's), since only the
    /// port changes in an answer (RFC 9429 5.3.1).
    pub(crate) rejected_name: Option<MediaName>,
    /// In an answer, the direction the section states: the transceiver's [[Direction]]
    /// intersected with the reverse of the offered direction (RFC 9429 section 5.3.1). `None`
    /// in an offer, which states [[Direction]].
    pub(crate) answer_direction: Option<RTCRtpTransceiverDirection>,
    pub(crate) match_extensions: HashMap<String, u16>,
    pub(crate) rid_map: Vec<SimulcastRid>,
    /// In an answer, the `<proto>` of the offered m= line, which the answer repeats (RFC 9429
    /// section 5.1.2: "The profile in any 'm=' line in any generated answer MUST exactly match
    /// the profile provided in the offer"). `None` in an offer, which states this endpoint's
    /// own profile.
    pub(crate) offered_protos: Option<Vec<String>>,
}

/// The profiles of a media (RTP) m= line RFC 9429 section 5.1.2 has accepted in an offer:
/// whatever the string, the section is DTLS-SRTP with feedback when it carries
/// `a=fingerprint`.
const RTP_PROFILES: [&str; 8] = [
    "RTP/AVP",
    "RTP/AVPF",
    "RTP/SAVP",
    "RTP/SAVPF",
    "TCP/DTLS/RTP/SAVP",
    "TCP/DTLS/RTP/SAVPF",
    "UDP/TLS/RTP/SAVP",
    "UDP/TLS/RTP/SAVPF",
];

/// Whether an audio or video m= line's `<proto>` is one of the RTP profiles RFC 9429 section
/// 5.1.2 lists. Another one (`udptl`, say) is not RTP this endpoint can answer.
pub(crate) fn is_rtp_profile(media: &MediaDescription) -> bool {
    RTP_PROFILES.contains(&media.media_name.protos.join("/").as_str())
}

pub(crate) struct PopulateSdpParams {
    pub(crate) media_description_fingerprint: bool,
    pub(crate) is_ice_lite: bool,
    pub(crate) is_extmap_allow_mixed: bool,
    pub(crate) connection_role: ConnectionRole,
    pub(crate) ice_gathering_state: RTCIceGatheringState,
    pub(crate) bundle: BundleMode,
    pub(crate) sctp_max_message_size: usize,
    pub(crate) ignore_rid_pause_for_recv: bool,
    pub(crate) write_ssrc_attributes_for_simulcast: bool,
}

impl RTCPeerConnection {
    /// Each mid's first transceiver in `local_transceivers`, so a pass over every m-section of
    /// a description looks mids up instead of scanning the transceivers for each one.
    pub(crate) fn transceiver_index_by_mid(
        local_transceivers: &[RTCRtpTransceiverInternal],
    ) -> HashMap<String, usize> {
        let mut by_mid = HashMap::with_capacity(local_transceivers.len());
        for (i, t) in local_transceivers.iter().enumerate() {
            if let Some(mid) = t.mid() {
                by_mid.entry(mid.clone()).or_insert(i);
            }
        }
        by_mid
    }

    /// Given a direction+type pluck a transceiver from the passed list and return its index;
    /// `None` when no entry satisfies the requested type+direction
    pub(crate) fn satisfy_type_and_direction(
        remote_kind: RtpCodecKind,
        remote_direction: RTCRtpTransceiverDirection,
        local_transceivers: &[RTCRtpTransceiverInternal],
    ) -> Option<usize> {
        // Get direction order from most preferred to least
        let get_preferred_directions = || -> Vec<RTCRtpTransceiverDirection> {
            match remote_direction {
                RTCRtpTransceiverDirection::Sendrecv => vec![
                    RTCRtpTransceiverDirection::Recvonly,
                    RTCRtpTransceiverDirection::Sendrecv,
                ],
                RTCRtpTransceiverDirection::Sendonly => vec![RTCRtpTransceiverDirection::Recvonly],
                RTCRtpTransceiverDirection::Recvonly => vec![
                    RTCRtpTransceiverDirection::Sendonly,
                    RTCRtpTransceiverDirection::Sendrecv,
                ],
                _ => vec![],
            }
        };

        for possible_direction in get_preferred_directions() {
            // Find the index first to avoid multiple mutable borrows
            if let Some(index) = local_transceivers.iter().position(|t| {
                t.mid().is_none()
                    && !t.stopped()
                    && t.associable_with_remote_offer()
                    && t.kind() == remote_kind
                    && possible_direction == t.direction()
            }) {
                return Some(index);
            }
        }

        None
    }

    /// populate_sdp serializes a PeerConnections state into an SDP
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn populate_sdp(
        mut d: SessionDescription,
        dtls_fingerprints: &[RTCDtlsFingerprint],
        media_engine: &MediaEngine,
        transceivers: &mut [RTCRtpTransceiverInternal],
        candidates: &[RTCIceCandidate],
        ice_params: &RTCIceParameters,
        media_sections: &[MediaSection],
        params: PopulateSdpParams,
    ) -> Result<SessionDescription> {
        let media_dtls_fingerprints = if params.media_description_fingerprint {
            dtls_fingerprints.to_vec()
        } else {
            vec![]
        };

        // The mids of the BUNDLE group, in media section order.
        let mut bundled: Vec<String> = vec![];

        let mut candidates_added = false;
        for m in media_sections.iter() {
            // RFC 8829 §5.3.1: reflect rejected m-lines (port=0) in the answer.
            // These must appear in the same position as in the offer to preserve m-line indexing.
            if m.rejected {
                let (rejected_protos, rejected_formats) = if let Some(name) = &m.rejected_name {
                    (name.protos.clone(), name.formats.clone())
                } else if m.rejected_kind == "application" {
                    (
                        vec!["UDP".to_owned(), "DTLS".to_owned(), "SCTP".to_owned()],
                        vec!["webrtc-datachannel".to_owned()],
                    )
                } else {
                    (
                        vec![
                            "UDP".to_owned(),
                            "TLS".to_owned(),
                            "RTP".to_owned(),
                            "SAVPF".to_owned(),
                        ],
                        vec!["0".to_owned()],
                    )
                };

                d = d.with_media(
                    MediaDescription {
                        media_name: MediaName {
                            media: m.rejected_kind.clone(),
                            port: RangedPort {
                                value: 0,
                                range: None,
                            },
                            protos: rejected_protos,
                            formats: rejected_formats,
                        },
                        media_title: None,
                        connection_information: Some(ConnectionInformation {
                            network_type: "IN".to_owned(),
                            address_type: "IP4".to_owned(),
                            address: Some(Address {
                                address: "0.0.0.0".to_owned(),
                                ttl: None,
                                range: None,
                            }),
                        }),
                        bandwidth: vec![],
                        encryption_key: None,
                        attributes: vec![],
                    }
                    .with_value_attribute(ATTR_KEY_MID.to_owned(), m.mid.clone()),
                );
                if let (Some(protos), Some(desc)) =
                    (&m.offered_protos, d.media_descriptions.last_mut())
                {
                    desc.media_name.protos.clone_from(protos);
                }
                if m.stopped
                    && let Some(desc) = d.media_descriptions.last_mut()
                {
                    let rejected = std::mem::take(desc);
                    *desc = rejected.with_property_attribute("inactive".to_owned());
                }
                continue; // rejected m-lines are not added to BUNDLE
            }

            if m.data && m.transceiver_index != usize::MAX {
                return Err(Error::ErrSDPMediaSectionMediaDataChanInvalid);
            } else if !m.data && m.transceiver_index >= transceivers.len() {
                return Err(Error::ErrSDPMediaSectionTrackInvalid);
            }

            let should_add_candidates = !candidates_added;

            let should_add_id = if m.data {
                let params = AddDataMediaSectionParams {
                    should_add_candidates,
                    mid_value: m.mid.clone(),
                    ice_params: ice_params.clone(),
                    dtls_role: params.connection_role,
                    ice_gathering_state: params.ice_gathering_state,
                    sctp_max_message_size: params.sctp_max_message_size,
                };
                d = add_data_media_section(d, &media_dtls_fingerprints, candidates, params)?;
                true
            } else {
                let params = AddTransceiverSdpParams {
                    should_add_candidates,
                    mid_value: m.mid.clone(),
                    dtls_role: params.connection_role,
                    ice_gathering_state: params.ice_gathering_state,
                    ignore_rid_pause_for_recv: params.ignore_rid_pause_for_recv,
                    write_ssrc_attributes_for_simulcast: params.write_ssrc_attributes_for_simulcast,
                    is_offer: params.bundle == BundleMode::Offer,
                };
                let (d1, should_add_id) = RTCPeerConnection::add_transceiver_sdp(
                    d,
                    &media_dtls_fingerprints,
                    media_engine,
                    transceivers,
                    ice_params,
                    candidates,
                    m,
                    params,
                )?;
                d = d1;
                should_add_id
            };

            candidates_added = true;

            if let (Some(protos), Some(desc)) = (&m.offered_protos, d.media_descriptions.last_mut())
            {
                desc.media_name.protos.clone_from(protos);
            }

            if should_add_id {
                match &params.bundle {
                    BundleMode::Offer => bundled.push(m.mid.clone()),
                    BundleMode::Answer(Some(group)) if group.contains(&m.mid) => {
                        bundled.push(m.mid.clone())
                    }
                    BundleMode::Answer(Some(_)) => {
                        // Outside the offered group: it would need a transport of its own.
                        if let Some(desc) = d.media_descriptions.last_mut() {
                            desc.media_name.port = RangedPort {
                                value: 0,
                                range: None,
                            }
                        }
                    }
                    BundleMode::Answer(None) => {}
                }
            }
        }

        if !params.media_description_fingerprint {
            for fingerprint in dtls_fingerprints {
                d = d.with_fingerprint(
                    fingerprint.algorithm.clone(),
                    fingerprint.value.to_uppercase(),
                );
            }
        }

        if params.is_ice_lite {
            // RFC 8839 §5.3
            d = d.with_property_attribute(ATTR_KEY_ICELITE.to_owned());
        } else {
            // JSEP RFC 8829 §5.2.1 / §5.3.1: this side accepts trickled candidates
            // (`add_remote_candidate` at any time after the remote description), so it says so
            // (RFC 8840 §4.1.1). A lite agent has no checks to trickle into.
            d = d.with_value_attribute(ATTR_KEY_ICE_OPTIONS.to_owned(), "trickle".to_owned());
        }

        if params.is_extmap_allow_mixed {
            // RFC 8285 6.
            d = d.with_property_attribute(ATTR_KEY_EXTMAP_ALLOW_MIXED.to_owned());
        }

        if let BundleMode::Answer(Some(group)) = &params.bundle {
            // The offer's order: its first accepted tag is the answerer-tagged section.
            bundled.sort_by_key(|mid| group.iter().position(|tag| tag == mid));
        }
        if !bundled.is_empty() {
            d = d.with_value_attribute(
                ATTR_KEY_GROUP.to_owned(),
                format!("BUNDLE {}", bundled.join(" ")),
            );
        }

        Ok(d)
    }
}

pub(crate) fn get_mid_value(media: &MediaDescription) -> Option<&String> {
    for attr in &media.attributes {
        if attr.key == "mid" {
            return attr.value.as_ref();
        }
    }
    None
}

pub(crate) fn get_peer_direction(media: &MediaDescription) -> RTCRtpTransceiverDirection {
    for a in &media.attributes {
        let direction = RTCRtpTransceiverDirection::from(a.key.as_str());
        if direction != RTCRtpTransceiverDirection::Unspecified {
            return direction;
        }
    }
    RTCRtpTransceiverDirection::Unspecified
}

/// Extracts the remote DTLS fingerprints (RFC 8122 §5).
///
/// A section carries one `a=fingerprint` line per certificate and hash function (W3C
/// `RTCPeerConnection` writes one for each of its certificates), and the peer's certificate must
/// match one of them, so all of them are returned, the sha-256 ones (the algorithm DTLS
/// verification uses) first. Fingerprints may be given at session level and in every m-section;
/// the levels must agree on the sha-256 values when they have any (else on every value), or the
/// description is [`Error::ErrSessionDescriptionConflictingFingerprints`].
pub(crate) fn extract_fingerprints(desc: &SessionDescription) -> Result<Vec<RTCDtlsFingerprint>> {
    let parse =
        |attributes: &[sdp::description::common::Attribute]| -> Result<Vec<RTCDtlsFingerprint>> {
            let mut fingerprints = vec![];
            for value in attributes
                .iter()
                .filter(|a| a.key == "fingerprint")
                .filter_map(|a| a.value.as_deref())
            {
                let parts: Vec<&str> = value.split(' ').collect();
                if parts.len() != 2 {
                    return Err(Error::ErrSessionDescriptionInvalidFingerprint);
                }
                fingerprints.push(RTCDtlsFingerprint {
                    algorithm: parts[0].to_owned(),
                    value: parts[1].to_owned(),
                });
            }
            // sha-256 first; the order within an algorithm is kept.
            fingerprints.sort_by_key(|f| !f.algorithm.eq_ignore_ascii_case("sha-256"));
            Ok(fingerprints)
        };
    let compared = |fingerprints: &[RTCDtlsFingerprint]| -> Vec<(String, String)> {
        let has_sha256 = fingerprints
            .iter()
            .any(|f| f.algorithm.eq_ignore_ascii_case("sha-256"));
        let mut set: Vec<(String, String)> = fingerprints
            .iter()
            .filter(|f| !has_sha256 || f.algorithm.eq_ignore_ascii_case("sha-256"))
            .map(|f| (f.algorithm.to_lowercase(), f.value.to_lowercase()))
            .collect();
        set.sort();
        set.dedup();
        set
    };

    let mut levels = vec![parse(&desc.attributes)?];
    for m in &desc.media_descriptions {
        levels.push(parse(&m.attributes)?);
    }
    levels.retain(|level| !level.is_empty());

    let Some(first) = levels.first() else {
        return Err(Error::ErrSessionDescriptionNoFingerprint);
    };
    let expected = compared(first);
    if levels[1..].iter().any(|level| compared(level) != expected) {
        return Err(Error::ErrSessionDescriptionConflictingFingerprints);
    }

    Ok(levels.swap_remove(0))
}

/// Inserts `a=<key>[:<value>]` at the end of m-section `index` of an SDP text, keeping every
/// other byte, with the text's own line ending. Returns the text unchanged if it has no such
/// m-section.
pub(crate) fn insert_media_line(sdp: &str, index: usize, key: &str, value: Option<&str>) -> String {
    let eol = if sdp.contains("\r\n") { "\r\n" } else { "\n" };
    let mut starts = vec![];
    let mut offset = 0;
    for line in sdp.split_inclusive('\n') {
        if line.starts_with("m=") {
            starts.push(offset);
        }
        offset += line.len();
    }
    if index >= starts.len() {
        return sdp.to_owned();
    }
    let end = starts.get(index + 1).copied().unwrap_or(sdp.len());
    let mut out = String::with_capacity(sdp.len() + key.len() + 64);
    out.push_str(&sdp[..end]);
    if !out.ends_with('\n') {
        out.push_str(eol);
    }
    out.push_str("a=");
    out.push_str(key);
    if let Some(value) = value {
        out.push(':');
        out.push_str(value);
    }
    out.push_str(eol);
    out.push_str(&sdp[end..]);
    out
}

/// The remote ICE credentials and candidates of a session description.
#[derive(Debug, Clone)]
pub(crate) struct RemoteIceDetails {
    pub(crate) ufrag: String,
    pub(crate) pwd: String,
    pub(crate) candidates: Vec<Candidate>,
}

/// Whether an m-section is rejected: port zero without `a=bundle-only` (RFC 8843 §6, an
/// m-section that is only reachable through its BUNDLE group also has port zero).
pub(crate) fn is_rejected_media(m: &MediaDescription) -> bool {
    m.media_name.port.value == 0 && !m.has_attribute(ATTR_KEY_BUNDLE_ONLY)
}

/// Whether `s` is a `token` of RFC 8866 section 9: one or more of the characters
/// `!#$%&'*+-.0-9A-Z^_`a-z{|}~`.
pub(crate) fn is_sdp_token(s: &str) -> bool {
    !s.is_empty()
        && s.bytes().all(|b| {
            matches!(b,
                0x21 | 0x23..=0x27 | 0x2A..=0x2B | 0x2D..=0x2E | 0x30..=0x39 | 0x41..=0x5A
                | 0x5E..=0x7E)
        })
}

/// Drops the `a=bundle-only` attributes of a received description that do not mean
/// "this section has port zero because it is only reachable through its BUNDLE group":
///
/// - RFC 9143 section 6: "If an offerer or answerer receives a 'bundle-only' attribute in a
///   non-bundled 'm=' section, the offerer or answerer MUST discard the attribute." Without
///   it a port-zero section is what port zero says: rejected (RFC 3264 section 6).
/// - RFC 9143 sections 7.3.2 and 7.3.3 and RFC 9429 section 5.3.1: no m= section of an
///   answer has the attribute, so one in an answer is discarded too.
///
/// Only the parsed description changes: the SDP text stays as given.
pub(crate) fn discard_stray_bundle_only(desc: &mut SessionDescription, answers: bool) {
    let bundled: HashSet<String> = bundle_groups(desc)
        .into_iter()
        .flatten()
        .map(str::to_owned)
        .collect();
    for media in &mut desc.media_descriptions {
        let in_group = get_mid_value(media).is_some_and(|mid| bundled.contains(mid.as_str()));
        if answers || !in_group {
            media.attributes.retain(|a| a.key != ATTR_KEY_BUNDLE_ONLY);
        }
    }
}

/// The mids of the description's first `a=group:BUNDLE` (RFC 8843 §7.1), in order.
pub(crate) fn bundle_group_mids(desc: &SessionDescription) -> Vec<&str> {
    desc.attributes
        .iter()
        .filter(|a| a.key == ATTR_KEY_GROUP)
        .filter_map(|a| a.value.as_deref())
        .find_map(|value| {
            let mut tokens = value.split_whitespace();
            (tokens.next() == Some("BUNDLE")).then(|| tokens.collect())
        })
        .unwrap_or_default()
}

/// An m-section's ICE credentials: its own `a=ice-ufrag` / `a=ice-pwd`, else the session's
/// (RFC 8839 §5.4 allows both levels).
pub(crate) fn media_ice_credentials<'a>(
    desc: &'a SessionDescription,
    m: &'a MediaDescription,
) -> (Option<&'a str>, Option<&'a str>) {
    let ufrag = m
        .attribute("ice-ufrag")
        .flatten()
        .or_else(|| desc.attribute("ice-ufrag").map(String::as_str));
    let pwd = m
        .attribute("ice-pwd")
        .flatten()
        .or_else(|| desc.attribute("ice-pwd").map(String::as_str));
    (ufrag, pwd)
}

/// Checks ICE credentials against RFC 8839 §5.4: `ice-ufrag` is 4 to 256 ice-chars, `ice-pwd`
/// 22 to 256, an ice-char being ALPHA, DIGIT, "+" or "/" (RFC 8839 §5.1).
fn check_ice_credentials(ufrag: Option<&str>, pwd: Option<&str>) -> Result<()> {
    let valid = |value: &str, min: usize| {
        (min..=256).contains(&value.len())
            && value
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'+' || b == b'/')
    };
    if ufrag.is_some_and(|u| !valid(u, 4)) || pwd.is_some_and(|p| !valid(p, 22)) {
        return Err(Error::ErrSessionDescriptionInvalidIceCredentials);
    }
    Ok(())
}

/// Extracts the credentials and candidates of the ICE transport a remote description sets up.
///
/// This peer connection runs one ICE transport for every m-section, so the description has to
/// name one set of credentials:
///
/// - With a BUNDLE group, that is the offerer-tagged m-section's (the first mid of the group
///   that isn't rejected, RFC 8843 §7.2). The other m-sections of the group may carry their own
///   credentials (an offer under the `balanced` or `max-compat` policy does, JSEP RFC 8829
///   §5.2.1): their transports are discarded once BUNDLE is negotiated (RFC 8843 §7.3.3), so
///   their credentials and candidates aren't used.
/// - Every m-section outside the group must share those credentials; one that doesn't is
///   [`Error::ErrSessionDescriptionConflictingIceUfrag`] /
///   [`Error::ErrSessionDescriptionConflictingIcePwd`]. An inactive one is let through (its
///   credentials are the fallback when every m-section is inactive).
/// - Rejected m-sections set up no transport and are skipped.
///
/// Returns `Ok(None)` when there is no transport to set up: no m-section other than rejected
/// ones, and no session-level credentials (the description of a connection that has nothing to
/// negotiate yet, such as an offer created before any transceiver or data channel was added).
pub(crate) fn extract_ice_details(desc: &SessionDescription) -> Result<Option<RemoteIceDetails>> {
    let bundle = bundle_group_mids(desc);
    let bundle_set: HashSet<&str> = bundle.iter().copied().collect();
    let in_bundle = |m: &MediaDescription| {
        get_mid_value(m).is_some_and(|mid| bundle_set.contains(mid.as_str()))
    };
    // The first m-section that isn't rejected, for each mid: a lookup per bundle mid instead of
    // a scan of every m-section.
    let mut usable_by_mid: HashMap<&str, &MediaDescription> = HashMap::new();
    for m in &desc.media_descriptions {
        if let Some(mid) = get_mid_value(m)
            && !is_rejected_media(m)
        {
            usable_by_mid.entry(mid.as_str()).or_insert(m);
        }
    }
    let tagged = bundle
        .iter()
        .find_map(|mid| usable_by_mid.get(mid).copied());

    // Backup ufrag/pwd is the first inactive credentials found, for the corner case where all
    // media lines/transceivers are set to inactive.
    let mut backup_ufrag = None;
    let mut backup_pwd = None;

    let (mut remote_ufrag, mut remote_pwd) = match tagged {
        Some(m) => media_ice_credentials(desc, m),
        None => (
            desc.attribute("ice-ufrag").map(String::as_str),
            desc.attribute("ice-pwd").map(String::as_str),
        ),
    };

    let mut has_transport = remote_ufrag.is_some() || remote_pwd.is_some() || tagged.is_some();
    let mut transport_media = vec![];
    for m in &desc.media_descriptions {
        if is_rejected_media(m) {
            continue;
        }
        has_transport = true;
        let (ufrag, pwd) = media_ice_credentials(desc, m);
        check_ice_credentials(ufrag, pwd)?;

        if tagged.is_some() && in_bundle(m) {
            // Part of the tagged m-section's transport only when it says so with the same
            // credentials; otherwise its own transport, which BUNDLE replaces.
            if (ufrag.is_none() || ufrag == remote_ufrag) && (pwd.is_none() || pwd == remote_pwd) {
                transport_media.push(m);
            }
            continue;
        }

        if m.attribute(ATTR_KEY_INACTIVE).is_some() {
            if backup_ufrag.is_none() {
                backup_ufrag = ufrag;
            }
            if backup_pwd.is_none() {
                backup_pwd = pwd;
            }
            continue;
        }

        if remote_ufrag.is_none() {
            remote_ufrag = ufrag;
        }
        if remote_pwd.is_none() {
            remote_pwd = pwd;
        }

        if ufrag.is_some() && ufrag != remote_ufrag {
            return Err(Error::ErrSessionDescriptionConflictingIceUfrag);
        }
        if pwd.is_some() && pwd != remote_pwd {
            return Err(Error::ErrSessionDescriptionConflictingIcePwd);
        }
        transport_media.push(m);
    }

    if !has_transport {
        return Ok(None);
    }
    check_ice_credentials(remote_ufrag, remote_pwd)?;

    let remote_ufrag = remote_ufrag
        .or(backup_ufrag)
        .ok_or(Error::ErrSessionDescriptionMissingIceUfrag)?;
    let remote_pwd = remote_pwd
        .or(backup_pwd)
        .ok_or(Error::ErrSessionDescriptionMissingIcePwd)?;

    let mut candidates = vec![];
    for m in transport_media {
        for a in &m.attributes {
            if a.is_ice_candidate()
                && let Some(value) = &a.value
            {
                candidates.push(unmarshal_candidate(value)?);
            }
        }
    }

    Ok(Some(RemoteIceDetails {
        ufrag: remote_ufrag.to_owned(),
        pwd: remote_pwd.to_owned(),
        candidates,
    }))
}

pub(crate) fn is_lite_set(desc: &SessionDescription) -> bool {
    for a in &desc.attributes {
        if a.key.trim() == ATTR_KEY_ICELITE {
            return true;
        }
    }
    false
}

pub(crate) trait MediaDescriptionExt {
    /// Reports whether `self` is the WebRTC SCTP data channel m-line, as opposed to some
    /// other RTP-carried media that also uses the SDP media name `"application"`.
    fn is_webrtc_datachannel(&self) -> bool;
}

impl MediaDescriptionExt for MediaDescription {
    fn is_webrtc_datachannel(&self) -> bool {
        self.media_name.media == MEDIA_SECTION_APPLICATION
            && self.media_name.formats == ["webrtc-datachannel"]
    }
}

pub(crate) fn get_application_media_section_sctp_port(
    media_desc: &MediaDescription,
) -> Option<u16> {
    if media_desc.is_webrtc_datachannel() {
        return if let Some(sctp_port_attr) = media_desc
            .attributes
            .iter()
            .find(|attr| attr.key == "sctp-port")
        {
            let sctp_port_value = sctp_port_attr.value.as_ref();

            sctp_port_value.and_then(|attr| attr.parse::<u16>().ok())
        } else if let Some(sctp_port_attr) = media_desc
            .attributes
            .iter()
            .find(|attr| attr.key == "sctpmap")
        {
            if let Some(sctp_port_attr_value) = sctp_port_attr.value.as_ref() {
                sctp_port_attr_value
                    .split(" ")
                    .next()
                    .and_then(|port| u16::from_str(port).ok())
            } else {
                None
            }
        } else {
            None
        };
    }

    None
}

