pub(crate) fn rtp_extensions_from_media_description(
    m: &MediaDescription,
) -> Result<HashMap<String, u16>> {
    let mut out = HashMap::new();

    for a in &m.attributes {
        if a.key == ATTR_KEY_EXT_MAP {
            // RFC 8285 section 5 / JSEP (RFC 9429 section 5.10): an extension the answerer
            // doesn't understand is left out of the answer, not an error. A URI that isn't
            // even a URI (`a=extmap:2 bogus`) is such an extension; a malformed id or
            // direction still fails the description.
            if a.value
                .as_deref()
                .and_then(|v| v.split_whitespace().nth(1))
                .is_some_and(|uri| Url::parse(uri).is_err())
            {
                continue;
            }
            // RFC 8285 sections 5 and 6: 256 is the `appbits` mapping and 4096 to 4351 are
            // extensions the offerer left for the answerer to number. Neither is an id a
            // packet carries (`ExtMap::is_element_id`). They are valid in a description, so
            // they do not fail it; this endpoint does not use them, which leaves them out of
            // the answer (an answerer "MAY" take a 4096+ extension by renumbering it).
            if a.value
                .as_deref()
                .and_then(|v| v.split([' ', '/']).next())
                .and_then(|id| id.parse::<u32>().ok())
                .is_some_and(|id| id == 256 || (4096..=4351).contains(&id))
            {
                continue;
            }
            let a_str = a.to_string();
            let e = ExtMap::unmarshal(&mut a_str.as_bytes())?;

            if let Some(uri) = e.uri {
                out.insert(uri.to_string(), e.value);
            }
        }
    }

    Ok(out)
}

#[test]
fn rtp_extensions_from_media_description_reads_each_extmap_line() {
    let m = MediaDescription::default()
        .with_value_attribute("mid".to_owned(), "0".to_owned())
        .with_value_attribute(
            ATTR_KEY_EXT_MAP.to_owned(),
            "1 urn:ietf:params:rtp-hdrext:sdes:mid".to_owned(),
        )
        .with_value_attribute(
            ATTR_KEY_EXT_MAP.to_owned(),
            "3/recvonly urn:ietf:params:rtp-hdrext:ssrc-audio-level".to_owned(),
        );

    let extensions = rtp_extensions_from_media_description(&m).unwrap();

    assert_eq!(extensions.len(), 2);
    assert_eq!(extensions["urn:ietf:params:rtp-hdrext:sdes:mid"], 1);
    assert_eq!(extensions["urn:ietf:params:rtp-hdrext:ssrc-audio-level"], 3);

    let malformed = MediaDescription::default()
        .with_value_attribute(ATTR_KEY_EXT_MAP.to_owned(), "not-a-number urn:x".to_owned());
    assert!(rtp_extensions_from_media_description(&malformed).is_err());

    // An unknown extension whose name isn't a URI is skipped, not an error.
    let bogus = MediaDescription::default()
        .with_value_attribute(ATTR_KEY_EXT_MAP.to_owned(), "2 bogus".to_owned())
        .with_value_attribute(
            ATTR_KEY_EXT_MAP.to_owned(),
            "16 urn:ietf:params:rtp-hdrext:sdes:mid".to_owned(),
        );
    let extensions = rtp_extensions_from_media_description(&bogus).unwrap();
    assert_eq!(extensions.len(), 1);
    assert_eq!(extensions["urn:ietf:params:rtp-hdrext:sdes:mid"], 16);
}

#[test]
fn reoffered_header_extensions_adds_listed_extensions_back() {
    use crate::rtp_transceiver::rtp_sender::RTCRtpHeaderExtensionCapability;

    let mut media_engine = MediaEngine::default();
    for uri in [
        "urn:ietf:params:rtp-hdrext:sdes:mid",
        "urn:3gpp:video-orientation",
        "urn:ietf:params:rtp-hdrext:ssrc-audio-level",
    ] {
        let kind = if uri.ends_with("audio-level") {
            RtpCodecKind::Audio
        } else {
            RtpCodecKind::Video
        };
        media_engine
            .register_header_extension(
                RTCRtpHeaderExtensionCapability {
                    uri: uri.to_owned(),
                },
                kind,
                None,
            )
            .unwrap();
    }
    let listed = vec![
        "urn:ietf:params:rtp-hdrext:sdes:mid".to_owned(),
        "urn:3gpp:video-orientation".to_owned(),
        "urn:ietf:params:rtp-hdrext:ssrc-audio-level".to_owned(),
        "urn:example:unregistered".to_owned(),
    ];
    let written = vec![(1u16, "urn:ietf:params:rtp-hdrext:sdes:mid".to_owned())];
    let added = reoffered_header_extensions(
        &media_engine,
        RtpCodecKind::Video,
        RTCRtpTransceiverDirection::Sendrecv,
        &listed,
        &written,
    );
    // Only the registered video extension that isn't written yet, on a free id.
    assert_eq!(added, vec![(2u16, "urn:3gpp:video-orientation".to_owned())]);
}

/// Gives a generated description the session's `o=` line (RFC 9429 sections 5.2.2 and 5.3.2:
/// "The 'o=' line MUST stay the same except for the <session-version> field, which MUST
/// increment by one on each call ... if the offer might differ from the output of the
/// previous call"; RFC 3264 section 8: "the version in the origin field MUST increment by one
/// from the previous SDP").
///
/// The first description generated sets the session's origin (`origin`). Each later one gets
/// that origin, with the version one higher than the previous description's when it differs
/// from it (`last_generated`, the text of the previous one) and the same version when it is
/// the same text. Offers and answers are one sequence: they describe one session.
pub(crate) fn update_sdp_origin(
    origin: &mut Origin,
    last_generated: &mut String,
    d: &mut SessionDescription,
) {
    if last_generated.is_empty() {
        *origin = d.origin.clone();
    } else {
        d.origin = origin.clone();
        if d.marshal() == *last_generated {
            return;
        }
        origin.session_version = origin.session_version.wrapping_add(1);
        d.origin.session_version = origin.session_version;
    }
    *last_generated = d.marshal();
}

pub(crate) fn is_ext_map_allow_mixed_set(
    remote_description: Option<&RTCSessionDescription>,
) -> bool {
    remote_description.is_some_and(|r| {
        r.parsed
            .as_ref()
            .is_some_and(|parsed| parsed.has_attribute(ATTR_KEY_EXTMAP_ALLOW_MIXED))
    })
}

/// Checks if the SDP indicates trickle ICE support.
///
/// Per RFC 8838 and RFC 9429 section 4.1.17, trickle ICE support is indicated by
/// the presence of "trickle" in space-separated "ice-options" attribute values
/// at either session level or media level.
///
/// # Parameters
///
/// * `desc` - The parsed SDP session description
///
/// # Returns
///
/// `true` if trickle ICE is supported, `false` otherwise
pub(crate) fn has_ice_trickle_option(desc: &SessionDescription) -> bool {
    // Check session-level ice-options attribute
    if let Some(value) = desc.attribute("ice-options")
        && value.split_whitespace().any(|opt| opt == "trickle")
    {
        return true;
    }

    // Check media-level ice-options attribute
    for media in &desc.media_descriptions {
        if let Some(Some(value)) = media.attribute("ice-options")
            && value.split_whitespace().any(|opt| opt == "trickle")
        {
            return true;
        }
    }

    false
}

