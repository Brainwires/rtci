//! DTLS 1.3 handshakes recorded between `openssl s_client` and `openssl s_server` (OpenSSL
//! 4.1.0, built from the release tarball, loopback inside a container), for the known-answer
//! tests in `openssl_kat_test.rs`. RFC 9147 publishes no test vectors; these are the values
//! of another implementation.
//!
//! Recorded with, for each cipher suite and group:
//!
//! ```text
//! openssl s_server -dtls1_3 -accept <port> -key key.pem -cert cert.pem -keylogfile server.keys \
//!     -msg -debug -use_srtp SRTP_AES128_CM_SHA1_80 -ciphersuites <suite> -groups <group> \
//!     -num_tickets 0 -naccept 1
//! openssl s_client -dtls1_3 -connect 127.0.0.1:<port> -keylogfile client.keys -msg -debug \
//!     -use_srtp SRTP_AES128_CM_SHA1_80 -ciphersuites <suite> -groups <group> \
//!     -keymatexport EXTRACTOR-dtls_srtp -keymatexportlen 60
//! ```
//!
//! with a line typed into each side and the client closed after it. `-msg` prints every
//! handshake message in the clear (reassembled, with its DTLS handshake header), `-debug`
//! the datagrams as sent and received, the key log the traffic secrets and the exporter
//! secret, and `-keymatexport` the exporter output. The server runs the cookie exchange, so
//! each handshake has a HelloRetryRequest and two ClientHellos. The values below are the
//! client's outputs, unedited. OpenSSL refuses `TLS_AES_128_CCM_8_SHA256` for DTLS 1.3 (RFC
//! 9147 section 4.5.3), so there is no recording of it.

use crate::cipher_suite::CipherSuiteId;

/// One handshake message as `-msg` printed it: the 12-byte DTLS handshake header and the
/// whole body.
pub(crate) struct Message {
    pub(crate) from_client: bool,
    pub(crate) bytes: &'static [u8],
}

/// One datagram as `-debug` printed it.
pub(crate) struct Datagram {
    pub(crate) from_client: bool,
    pub(crate) bytes: &'static [u8],
}

pub(crate) struct Recording {
    pub(crate) suite: CipherSuiteId,
    /// From the key log.
    pub(crate) client_handshake_traffic_secret: &'static [u8],
    pub(crate) server_handshake_traffic_secret: &'static [u8],
    pub(crate) client_traffic_secret_0: &'static [u8],
    pub(crate) server_traffic_secret_0: &'static [u8],
    pub(crate) exporter_secret: &'static [u8],
    /// `Keying material:` for the label `EXTRACTOR-dtls_srtp`, 60 bytes.
    pub(crate) exporter: &'static [u8],
    /// Every handshake message, in the order the client sent or received it.
    pub(crate) handshake: &'static [Message],
    /// Every datagram, in the order the client sent or received it.
    pub(crate) datagrams: &'static [Datagram],
}

