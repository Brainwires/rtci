/// A packet with neither CSRCs nor header extensions is protected as RFC 3711 has it, with
/// Cryptex on or off.
#[test]
fn cryptex_leaves_a_bare_packet_alone() {
    let plain: &[u8] = &[
        0x80, 0x0f, 0x12, 0x35, 0xde, 0xca, 0xfb, 0xad, 0xca, 0xfe, 0xba, 0xbe, 0xab, 0xab, 0xab,
        0xab,
    ];
    for profile in [
        ProtectionProfile::Aes128CmHmacSha1_80,
        ProtectionProfile::AeadAes128Gcm,
    ] {
        let with = context(profile, SEND).encrypt_rtp(plain).unwrap();
        let without = context(profile, Cryptex::default())
            .encrypt_rtp(plain)
            .unwrap();
        assert_eq!(with, without);
    }
}

/// RFC 9335 section 5.2: with Cryptex required, a packet whose header extensions are in the
/// clear is refused; one protected with Cryptex, or one with nothing to protect, is not.
#[test]
fn cryptex_required_refuses_clear_header_extensions() {
    let require = Cryptex {
        send: false,
        require: true,
    };
    for (profile, vectors) in [
        (ProtectionProfile::Aes128CmHmacSha1_80, AES_CM_VECTORS),
        (ProtectionProfile::AeadAes128Gcm, GCM_VECTORS),
    ] {
        let (_, plain, encrypted) = vectors[0];
        let clear = context(profile, Cryptex::default())
            .encrypt_rtp(plain)
            .unwrap();
        assert!(context(profile, require).decrypt_rtp(&clear).is_err());
        assert_eq!(
            &context(profile, require).decrypt_rtp(encrypted).unwrap()[..],
            plain
        );
    }
}

/// A packet with CSRCs and no extension gets an empty 0xC0DE extension (RFC 9335 section
/// 5.1), which survives decryption as an empty 0xBEDE one.
#[test]
fn cryptex_adds_an_empty_extension_for_csrcs() {
    let plain: &[u8] = &[
        0x81, 0x0f, 0x12, 0x35, 0xde, 0xca, 0xfb, 0xad, 0xca, 0xfe, 0xba, 0xbe, 0x00, 0x01, 0xe2,
        0x40, 0xab, 0xab, 0xab, 0xab,
    ];
    let encrypted = context(ProtectionProfile::Aes128CmHmacSha1_80, SEND)
        .encrypt_rtp(plain)
        .unwrap();
    assert_eq!(encrypted[0], 0x91);
    assert_eq!(&encrypted[16..20], &[0xc0, 0xde, 0x00, 0x00]);
    let decrypted = context(ProtectionProfile::Aes128CmHmacSha1_80, Cryptex::default())
        .decrypt_rtp(&encrypted)
        .unwrap();
    let mut header: Vec<u8> = plain[..16].to_vec();
    header[0] = 0x91;
    assert_eq!(&decrypted[..16], &header[..]);
    assert_eq!(&decrypted[16..20], &[0xbe, 0xde, 0x00, 0x00]);
    assert_eq!(&decrypted[20..], &plain[16..]);
}
