fn context(profile: ProtectionProfile, cryptex: Cryptex) -> Context {
    let (key, salt): (&[u8], &[u8]) = match profile {
        ProtectionProfile::AeadAes128Gcm => (&GCM_KEY, &GCM_SALT),
        _ => (&AES_CM_KEY, &AES_CM_SALT),
    };
    let mut context = Context::new(
        key,
        salt,
        profile,
        None,
        None,
        test_crypto_provider().crypto(),
    )
    .expect("context");
    context.set_cryptex(cryptex);
    context
}

const SEND: Cryptex = Cryptex {
    send: true,
    require: false,
};

fn check(profile: ProtectionProfile, vectors: &[Vector]) {
    for (name, plain, encrypted) in vectors {
        let out = context(profile, SEND)
            .encrypt_rtp(plain)
            .unwrap_or_else(|e| panic!("{name}: encrypt: {e}"));
        assert_eq!(&out[..], *encrypted, "{name}: encrypt");

        let out = context(profile, Cryptex::default())
            .decrypt_rtp(encrypted)
            .unwrap_or_else(|e| panic!("{name}: decrypt: {e}"));
        assert_eq!(&out[..], *plain, "{name}: decrypt");
    }
}

